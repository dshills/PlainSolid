var nonplanarMaterialCases = []struct {
	file            string
	kind, generated NonplanarSplineMaterialKind
	volume          float64
	shells          int
}{
	{"occt-parabolic-spline-roof.step", NonplanarQuadraticMaterial, NonplanarQuadraticMaterial, 28, 1},
	{"occt-cubic-spline-roof.step", NonplanarCubicMaterial, NonplanarCubicMaterial, 90, 1},
	{"occt-multispan-spline-roof.step", NonplanarMultispanUVMaterial, NonplanarQuadraticMaterial, 28, 1},
	{"occt-rational-speed-roof.step", NonplanarRationalSpeedMaterial, NonplanarQuadraticMaterial, 28, 1},
	{"occt-spline-roof-void.step", NonplanarCavityMaterial, NonplanarCavityMaterial, 27.5625, 2},
	{"occt-spline-roof-voids.step", NonplanarMultipleVoidsMaterial, NonplanarMultipleVoidsMaterial, 26.0859375, 3},
}

func nonplanarMaterialFixture(t testing.TB, file string) []byte {
	t.Helper()
	b, e := os.ReadFile(filepath.Join("testdata", file))
	if e != nil {
		t.Fatal(e)
	}
	return b
}
func TestNonplanarSplineMaterialFamilies(t *testing.T) {
	slowtest.Skip(t)
	ctx := context.Background()
	for _, c := range nonplanarMaterialCases {
		t.Run(string(c.kind), func(t *testing.T) {
			raw := nonplanarMaterialFixture(t, c.file)
			m, e := ReadNonplanarSplineMaterial(ctx, bytes.NewReader(raw), Limits{})
			if e != nil {
				t.Fatal(e)
			}
			p := m.Provenance()
			if m.Kind() != c.kind || m.OriginalSTEP() != string(raw) || len(p.ShellIDs) != c.shells || len(p.VoidOccurrenceIDs) != c.shells-1 || m.LengthUnit() != .001 {
				t.Fatal("classification", m.Kind(), p)
			}
			for i := range p.ShellIDs {
				if len(p.FaceIDs[i]) != 6 || len(p.EdgeIDs[i]) != 12 || len(p.PCurveIDs[i]) != 24 || len(p.SupportIDs[i]) != 6 || len(p.NativeFaces[i]) != 6 {
					t.Fatal("roles", p)
				}
			}
			var native bytes.Buffer
			if e = WriteNonplanarSplineMaterialJSON(ctx, &native, m); e != nil {
				t.Fatal(e)
			}
			loaded, e := ReadNonplanarSplineMaterialJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{})
			if e != nil || loaded.Kind() != c.kind {
				t.Fatal("native", e)
			}
			var stable bytes.Buffer
			if e = WriteNonplanarSplineMaterialJSON(ctx, &stable, loaded); e != nil || !bytes.Equal(native.Bytes(), stable.Bytes()) {
				t.Fatal("stable", e)
			}
			var source, generated bytes.Buffer
			if e = WriteNonplanarSplineMaterialSource(ctx, &source, loaded, Limits{}); e != nil || !bytes.Equal(raw, source.Bytes()) {
				t.Fatal("source", e)
			}
			if e = WriteNonplanarSplineMaterial(ctx, &generated, loaded, Limits{}); e != nil {
				t.Fatal(e)
			}
			normalized, e := ReadNonplanarSplineMaterial(ctx, bytes.NewReader(generated.Bytes()), Limits{})
			if e != nil || normalized.Kind() != c.generated || normalized.Name() != m.Name() || normalized.LengthUnit() != m.LengthUnit() {
				t.Fatal("generated", normalized.Kind(), e)
			}
			mass, e := normalized.Solid().MassProperties(ctx, parametric.IntegrationOptions{})
			if e != nil || math.Abs(mass.Volume-c.volume) > 1e-8 {
				t.Fatal(mass, e)
			}
			p.FaceIDs[0][0]++
			p.NativeFaces[0][0]++
			p.ShellIDs[0]++
			if p.FaceIDs[0][0] == m.Provenance().FaceIDs[0][0] || p.NativeFaces[0][0] == m.Provenance().NativeFaces[0][0] || p.ShellIDs[0] == m.Provenance().ShellIDs[0] {
				t.Fatal("mutable proof")
			}
		})
	}
}
func TestNonplanarSplineMaterialReject(t *testing.T) {
	ctx := context.Background()
	raw := nonplanarMaterialFixture(t, nonplanarMaterialCases[0].file)
	for name, edit := range map[string]func(*File){
		"planar-substitute": func(f *File) {
			for _, en := range f.Entities {
				for _, r := range en.Records {
					if r.Type == "CARTESIAN_POINT" && len(r.Args[1].Items) == 3 {
						q, e := affineSplineSourceRat(r.Args[1].Items[2])
						if e == nil && q.RatString() == "3" {
							r.Args[1].Items[2].Text = "2"
						}
					}
				}
			}
		},
		"mixed-body-roots": func(f *File) {
			f.Entities[99999] = Entity{ID: 99999, Records: []Record{{Type: "BREP_WITH_VOIDS", Args: []Value{{Kind: String}, {Kind: Reference, Ref: 16}, {Kind: Aggregate}}}}}
			f.Order = append(f.Order, 99999)
		},
		"unknown-pcurve": func(f *File) {
			for _, en := range f.Entities {
				for _, r := range en.Records {
					if r.Type == "PCURVE" {
						rep := f.Entities[r.Args[2].Ref].Records[0]
						id := rep.Args[1].Items[0].Ref
						f.Entities[id].Records[0].Type = "TRIMMED_CURVE"
						return
					}
				}
			}
		},
		"detached-rational-no-downgrade": func(f *File) {
			f.Entities[99999] = Entity{ID: 99999, Records: []Record{{Type: "RATIONAL_B_SPLINE_CURVE", Args: []Value{{Kind: Aggregate, Items: []Value{{Kind: Number, Text: "1"}}}}}}}
			f.Order = append(f.Order, 99999)
		},
		"near-degree": func(f *File) {
			for _, en := range f.Entities {
				for _, r := range en.Records {
					if r.Type == "B_SPLINE_SURFACE_WITH_KNOTS" {
						r.Args[1].Text = "2.000000000000000001"
						return
					}
				}
			}
		},
	} {
		t.Run(name, func(t *testing.T) {
			f, e := Parse(bytes.NewReader(raw), Limits{})
			if e != nil {
				t.Fatal(e)
			}
			edit(f)
			b, e := mappedPlanarSourceBytes(f)
			if e != nil {
				t.Fatal(e)
			}
			m, e := ReadNonplanarSplineMaterial(ctx, bytes.NewReader(b), Limits{})
			if e == nil || m.Kind() != "" || len(m.Solid().Faces()) != 0 {
				t.Fatal("accepted", e)
			}
		})
	}
	// A declared rational family cannot downgrade when one actual weight is bad.
	f, e := Parse(bytes.NewReader(nonplanarMaterialFixture(t, "occt-rational-speed-roof.step")), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	for _, en := range f.Entities {
		for _, r := range en.Records {
			if r.Type == "RATIONAL_B_SPLINE_CURVE" {
				r.Args[0].Items[0].Text = "0"
			}
		}
	}
	b, _ := mappedPlanarSourceBytes(f)
	if _, e = ReadNonplanarSplineMaterial(ctx, bytes.NewReader(b), Limits{}); e == nil {
		t.Fatal("rational downgrade")
	}
	m, e := ReadNonplanarSplineMaterial(ctx, bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	var native bytes.Buffer
	if e = WriteNonplanarSplineMaterialJSON(ctx, &native, m); e != nil {
		t.Fatal(e)
	}
	for _, edit := range []func(*nonplanarSplineMaterialEnvelope){func(q *nonplanarSplineMaterialEnvelope) { q.Kind = NonplanarCubicMaterial }, func(q *nonplanarSplineMaterialEnvelope) { q.Format = nonplanarSplineShellNativeFormat }, func(q *nonplanarSplineMaterialEnvelope) { q.Provenance.PCurveIDs[0][0]++ }, func(q *nonplanarSplineMaterialEnvelope) { q.Provenance.NativeFaces[0][0]++ }, func(q *nonplanarSplineMaterialEnvelope) { q.Native = json.RawMessage(`{}`) }, func(q *nonplanarSplineMaterialEnvelope) { q.LengthUnit = 1 }, func(q *nonplanarSplineMaterialEnvelope) {
		q.Source = string(nonplanarMaterialFixture(t, "occt-cubic-spline-roof.step"))
	}} {
		var q nonplanarSplineMaterialEnvelope
		json.Unmarshal(native.Bytes(), &q)
		edit(&q)
		b, _ := json.Marshal(q)
		if _, e = ReadNonplanarSplineMaterialJSON(ctx, bytes.NewReader(b), IndependentMaterialJSONLimits{}); e == nil {
			t.Fatal("forged envelope")
		}
	}
	for _, l := range []Limits{{MaxBytes: 10}, {MaxEntities: 10}, {MaxValues: 100}, {MaxDepth: 1}, {MaxFaces: 5}} {
		if _, e = ReadNonplanarSplineMaterial(ctx, bytes.NewReader(raw), l); e == nil {
			t.Fatal("limit")
		}
	}
	cancelled, cancel := context.WithCancel(ctx)
	cancel()
	if _, e = ReadNonplanarSplineMaterial(cancelled, bytes.NewReader(raw), Limits{}); e == nil {
		t.Fatal("cancel")
	}
	if _, e = ReadNonplanarSplineMaterialJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{MaxBytes: 10}); e == nil {
		t.Fatal("native limit")
	}
	m.kind = NonplanarCavityMaterial
	var out bytes.Buffer
	if e = WriteNonplanarSplineMaterialJSON(ctx, &out, m); e == nil || out.Len() != 0 {
		t.Fatal("internal tag forgery")
	}
	if e = WriteNonplanarSplineMaterial(ctx, &out, NonplanarSplineMaterial{}, Limits{}); e == nil {
		t.Fatal("zero material")
	}
}
func TestNonplanarSplineMaterialLive(t *testing.T) {
	bin := os.Getenv("PLAINSOLID_OCCT_SPLINE_ROOF_VOID")
	if bin == "" {
		t.Skip("independent STEP material comparator")
	}
	ctx := context.Background()
	for _, c := range nonplanarMaterialCases {
		t.Run(string(c.kind), func(t *testing.T) {
			raw := nonplanarMaterialFixture(t, c.file)
			m, e := ReadNonplanarSplineMaterial(ctx, bytes.NewReader(raw), Limits{})
			if e != nil {
				t.Fatal(e)
			}
			var native bytes.Buffer
			if e = WriteNonplanarSplineMaterialJSON(ctx, &native, m); e != nil {
				t.Fatal(e)
			}
			m, e = ReadNonplanarSplineMaterialJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{})
			if e != nil {
				t.Fatal(e)
			}
			for _, mode := range []string{"source", "generated"} {
				var out bytes.Buffer
				if mode == "source" {
					e = WriteNonplanarSplineMaterialSource(ctx, &out, m, Limits{})
				} else {
					e = WriteNonplanarSplineMaterial(ctx, &out, m, Limits{})
				}
				if e != nil {
					t.Fatal(e)
				}
				p := filepath.Join(t.TempDir(), mode+".step")
				if e = os.WriteFile(p, out.Bytes(), 0600); e != nil {
					t.Fatal(e)
				}
				b, e := exec.Command(bin, "read", p).CombinedOutput()
				if e != nil {
					t.Fatal(e, string(b))
				}
				var q struct {
					Volume        float64
					Solids, Faces int
				}
				found := false
				for _, line := range bytes.Split(b, []byte("\n")) {
					if json.Unmarshal(line, &q) == nil && q.Solids == 1 {
						found = true
						break
					}
				}
				if !found || q.Faces != 6*c.shells || math.Abs(q.Volume-c.volume) > 1e-8 {
					t.Fatal(mode, string(b))
				}
			}
		})
	}
}
func FuzzNonplanarSplineMaterial(f *testing.F) {
	for _, c := range nonplanarMaterialCases {
		f.Add(nonplanarMaterialFixture(f, c.file))
	}
	f.Fuzz(func(t *testing.T, b []byte) {
		if len(b) > 1<<20 {
			t.Skip()
		}
		ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
		defer cancel()
		m, e := ReadNonplanarSplineMaterial(ctx, bytes.NewReader(b), Limits{})
		if e != nil {
			if m.Kind() != "" || len(m.Solid().Faces()) != 0 {
				t.Fatal("partial")
			}
			return
		}
		if m.Kind() == "" || len(m.Provenance().ShellIDs) == 0 {
			t.Fatal("unproved")
		}
	})
}
