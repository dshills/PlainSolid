package step

import (
	"bytes"
	"context"
	"encoding/json"
	"math"
	"plainsolid/brep/edgecheck"
	"plainsolid/brep/parametric"
	"plainsolid/brep/trimmed"
	"plainsolid/geom"
	"plainsolid/internal/slowtest"
	"testing"
)

func TestNonplanarSplineCavityOriginal(t *testing.T) {
	slowtest.Skip(t)
	ctx := context.Background()
	raw := nonplanarCavityFixture(t)
	m, e := ReadNonplanarSplineCavitySource(ctx, bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	if _, e = ReadNonplanarSplineShellSource(ctx, bytes.NewReader(raw), Limits{}); e == nil {
		t.Fatal("old shell route widened")
	}
	if m.SourceShells()[0] == m.SourceShells()[1] || len(m.SourceFaces()[0]) != 6 || len(m.SourceEdges()[1]) != 12 || !m.History().BReversed {
		t.Fatal("ancestry")
	}
	p, e := m.Solid.ValidateNestedSplineComponents(ctx, trimmed.SplineShellBooleanOptions{})
	if e != nil || len(p) != 2 || p[0].Parent != -1 || p[1].Parent != 0 || p[1].Depth != 1 {
		t.Fatal(p, e)
	}
	mass, e := m.Solid.MassProperties(ctx, parametric.IntegrationOptions{})
	area := (12. + 56./3 + 15 + 3*math.Sqrt(5) + 12*math.Asinh(.5)) * 17 / 16
	if e != nil || math.Abs(mass.Volume-27.5625) > 1e-10 || math.Abs(mass.Area-area) > 1e-7 || math.Abs(mass.Centroid.X-3797./1764) > 1e-10 || math.Abs(mass.Centroid.Y-5299./3528) > 1e-10 || math.Abs(mass.Centroid.Z-4205./3528) > 1e-10 {
		t.Fatal(mass, e)
	}
	for i, nativeID := range m.History().FacesB {
		if nativeID < 0 || m.Solid.Faces()[nativeID].Reversed == m.Inner.Solid.Faces()[i].Reversed {
			t.Fatal("inner material face sense")
		}
	}
	for _, s := range []trimmed.Solid{m.Outer.Solid, m.Inner.Solid, m.Solid} {
		proof, e := s.ValidateEdgeAgreement(ctx, edgecheck.Options{})
		if e != nil || !proof.Complete {
			t.Fatal(e)
		}
		for _, u := range proof.Uses {
			if u.Report.SquaredUpperBound == nil || u.Report.SquaredUpperBound.Sign() != 0 {
				t.Fatal("nonzero edge discrepancy")
			}
		}
	}
	for _, q := range []struct {
		p geom.Vec3
		l parametric.Location
	}{{geom.Vec3{X: .5, Y: .5, Z: 1}, parametric.Inside}, {geom.Vec3{X: 1.5, Y: 1.25, Z: .75}, parametric.Outside}, {geom.Vec3{X: 1.5, Y: 1.25, Z: .5}, parametric.Boundary}} {
		got, e := m.Solid.LocateNestedSplineMaterial(ctx, q.p, trimmed.SplineShellBooleanOptions{})
		if e != nil || got != q.l {
			t.Fatal(q, got, e)
		}
	}
	var native bytes.Buffer
	if e = WriteNonplanarSplineCavitySourceJSON(ctx, &native, m); e != nil {
		t.Fatal(e)
	}
	loaded, e := ReadNonplanarSplineCavitySourceJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	var again bytes.Buffer
	if e = WriteNonplanarSplineCavitySourceJSON(ctx, &again, loaded); e != nil || !bytes.Equal(native.Bytes(), again.Bytes()) {
		t.Fatal("unstable", e)
	}
	var q nonplanarSplineCavityEnvelope
	json.Unmarshal(native.Bytes(), &q)
	ordinary, e := trimmed.ReadJSON(bytes.NewReader(q.Native), trimmed.JSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	p, e = ordinary.ValidateNestedSplineComponents(ctx, trimmed.SplineShellBooleanOptions{})
	if e != nil || len(p) != 2 || p[1].Depth != 1 {
		t.Fatal("native void", e)
	}
	var source, generated bytes.Buffer
	if e = WriteNonplanarSplineCavitySource(ctx, &source, loaded, Limits{}); e != nil || !bytes.Equal(source.Bytes(), raw) {
		t.Fatal("source", e)
	}
	if e = WriteNonplanarSplineCavity(ctx, &generated, loaded, Limits{}); e != nil {
		t.Fatal(e)
	}
	if _, e = ReadNonplanarSplineCavitySource(ctx, bytes.NewReader(generated.Bytes()), Limits{}); e != nil {
		t.Fatal("generated reproof", e)
	}
	f, e := Parse(bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	for i, j := 0, len(f.Order)-1; i < j; i, j = i+1, j-1 {
		f.Order[i], f.Order[j] = f.Order[j], f.Order[i]
	}
	reordered, e := mappedPlanarSourceBytes(f)
	if e != nil {
		t.Fatal(e)
	}
	if _, e = ReadNonplanarSplineCavitySource(ctx, bytes.NewReader(reordered), Limits{}); e != nil {
		t.Fatal("record order", e)
	}
	faces := m.SourceFaces()
	faces[0][0]++
	h := m.History()
	h.FacesB[0]++
	if faces[0][0] == m.SourceFaces()[0][0] || h.FacesB[0] == m.History().FacesB[0] {
		t.Fatal("mutable ancestry")
	}
}
