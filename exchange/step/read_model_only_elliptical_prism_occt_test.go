package step

import (
	"bytes"
	"context"
	"encoding/json"
	"math"
	"os"
	"os/exec"
	"path/filepath"
	"plainsolid/brep/parametric"
	"plainsolid/geom"
	"testing"
	"time"
)

func TestOCCTReadModelOnlyEllipticalPrism(t *testing.T) {
	bin := os.Getenv("PLAINSOLID_OCCT_ELLIPTICAL_PRISM")
	if bin == "" {
		t.Skip("optional pinned OCCT")
	}
	var generated bytes.Buffer
	if e := WriteEllipticalPrismMaterialSTEP(context.Background(), &generated, nativeEllipsePrism(t), EllipticalPrismSTEPOptions{Translation: geom.Vec3{X: 8, Y: -2, Z: 4}}); e != nil {
		t.Fatal(e)
	}
	m, e := ReadModelOnlyEllipticalPrism(context.Background(), &generated, Limits{}, 1e-9)
	if e != nil {
		t.Fatal(e)
	}
	var native bytes.Buffer
	if e = WriteModelOnlyEllipticalPrismJSON(context.Background(), &native, m); e != nil {
		t.Fatal(e)
	}
	m, e = ReadModelOnlyEllipticalPrismJSON(context.Background(), &native, Limits{})
	if e != nil {
		t.Fatal(e)
	}
	props, e := m.Solid.MassProperties(context.Background(), parametric.IntegrationOptions{RelativeTolerance: 1e-9})
	if e != nil {
		t.Fatal(e)
	}
	var out bytes.Buffer
	if e = WriteModelOnlyEllipticalPrismSource(context.Background(), &out, m.Source, Limits{}, 1e-9); e != nil {
		t.Fatal(e)
	}
	path := filepath.Join(t.TempDir(), "exact-native-reload.step")
	if e = os.WriteFile(path, out.Bytes(), 0600); e != nil {
		t.Fatal(e)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	b, e := exec.CommandContext(ctx, bin, "read", path).CombinedOutput()
	cancel()
	if e != nil {
		t.Fatal(e, string(b))
	}
	at := bytes.LastIndex(b, []byte(`{"Area"`))
	if at < 0 {
		t.Fatal(string(b))
	}
	var q struct {
		Area, Volume  float64
		Faces, Solids int
		SurfaceCenter [3]float64
	}
	if e = json.Unmarshal(b[at:], &q); e != nil {
		t.Fatal(e)
	}
	center := geom.Vec3{X: q.SurfaceCenter[0], Y: q.SurfaceCenter[1], Z: q.SurfaceCenter[2]}
	if q.Faces != 3 || q.Solids != 1 || math.Abs(q.Area-props.Area) > 1e-7 || math.Abs(q.Volume-props.Volume) > 1e-7 || center.Distance(props.Centroid) > 1e-8 {
		t.Fatal(q, props)
	}
}
