func independentAnalyticAssemblyModel(t testing.TB) IndependentAnalyticAssemblyModel {
	t.Helper()
	m := independentTorusAssemblyModel(t)
	raw, e := os.ReadFile("testdata/independent-cylinder-materials.step")
	if e != nil {
		t.Fatal(e)
	}
	c, e := ReadIndependentCylinderMaterials(context.Background(), bytes.NewReader(raw), Limits{}, 1e-9)
	if e != nil {
		t.Fatal(e)
	}
	var source *File
	for _, p := range c.Members {
		if p.Cylinder != nil && p.Cylinder.Cells == 4 {
			source = p.Source
		}
	}
	if source == nil {
		t.Fatal("cylinder source")
	}
	m.Products = append(m.Products, IndependentTorusAssemblyPart{ID: "cylinder", Name: "cylinder", Source: source})
	m.Occurrences = append(m.Occurrences, AssemblyInstance{ID: "cylinder", Parent: "root", Child: "cylinder", Transform: geom.Affine{{0, 0, 1, 0}, {1, 0, 0, -20}, {0, 1, 0, 10}}})
	return IndependentAnalyticAssemblyModel(m)
}
func TestIndependentAnalyticAssembly(t *testing.T) {
	t.Parallel()
	ctx := context.Background()
	raw, e := os.ReadFile("testdata/independent-analytic-assembly.step")
	if e != nil {
		t.Fatal(e)
	}
	a, e := ReadIndependentAnalyticAssembly(ctx, bytes.NewReader(raw), Limits{}, 1e-9)
	if e != nil {
		t.Fatal(e)
	}
	if len(a.Products) != 3 || len(a.Assembly.Occurrences) != 4 {
		t.Fatal("roles")
	}
	if _, e = ReadIndependentTorusAssembly(ctx, bytes.NewReader(raw), Limits{}, 1e-9); e == nil {
		t.Fatal("old widened")
	}
	old, e := os.ReadFile("testdata/independent-torus-assembly.step")
	if e != nil {
		t.Fatal(e)
	}
	if _, e = ReadIndependentAnalyticAssembly(ctx, bytes.NewReader(old), Limits{}, 1e-9); e == nil {
		t.Fatal("new requires cylinder")
	}
	var generated bytes.Buffer
	if e = WriteIndependentAnalyticAssembly(ctx, &generated, independentAnalyticAssemblyModel(t), Limits{}, 1e-9); e != nil {
		t.Fatal(e)
	}
	if _, e = ReadIndependentAnalyticAssembly(ctx, bytes.NewReader(generated.Bytes()), Limits{}, 1e-9); e != nil {
		t.Fatal(e)
	}
	var native bytes.Buffer
	if e = WriteIndependentAnalyticAssemblyJSON(ctx, &native, a); e != nil {
		t.Fatal(e)
	}
	reload, e := ReadIndependentAnalyticAssemblyJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	var stable bytes.Buffer
	if e = WriteIndependentAnalyticAssemblyJSON(ctx, &stable, reload); e != nil || !bytes.Equal(native.Bytes(), stable.Bytes()) {
		t.Fatal("native stable", e)
	}
	var source bytes.Buffer
	if e = WriteIndependentAnalyticAssemblySource(ctx, &source, reload.Assembly.Source, Limits{}, 1e-9); e != nil {
		t.Fatal(e)
	}
	for id, p := range a.Products {
		q := reload.Products[id]
		if p.SourceRootID != q.SourceRootID || p.SourceBodyID != q.SourceBodyID {
			t.Fatal("ancestry")
		}
		if p.Cylinder != nil {
			if p.Cylinder.Cells != 4 || p.Cylinder.Radius != 2 || p.Cylinder.Height != 3 {
				t.Fatal("cylinder")
			}
			x, _ := json.Marshal(p.Cylinder)
			y, _ := json.Marshal(q.Cylinder)
			if !bytes.Equal(x, y) {
				t.Fatal("cylinder roles")
			}
		}
	}
	if _, e = ReadIndependentTorusAssemblyJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{}); e == nil {
		t.Fatal("old tag")
	}
	_, oldNative := torusAssemblyNativeFixture(t)
	if _, e = ReadIndependentAnalyticAssemblyJSON(ctx, bytes.NewReader(oldNative), IndependentMaterialJSONLimits{}); e == nil {
		t.Fatal("new tag")
	}
	if oracle := os.Getenv("PLAINSOLID_OCCT_INDEPENDENT_TORUS_ASSEMBLY"); oracle != "" {
		for _, b := range [][]byte{raw, generated.Bytes(), source.Bytes()} {
			file := filepath.Join(t.TempDir(), "analytic.step")
			if e = os.WriteFile(file, b, 0600); e != nil {
				t.Fatal(e)
			}
			data, e := exec.Command(oracle, "read", file).CombinedOutput()
			if e != nil {
				t.Fatal(e, string(data))
			}
			at := bytes.LastIndex(data, []byte("{"))
			var q struct {
				Volume, Area            float64
				Solids, Faces, EdgeUses int
				Bounds                  [6]float64
				SurfaceCenter           [3]float64
			}
			if at < 0 || json.Unmarshal(data[at:], &q) != nil {
				t.Fatal(string(data))
			}
			area := 52 + 24*math.Pi*math.Pi + 20*math.Pi
			volume := 24 + 12*math.Pi*math.Pi + 12*math.Pi
			if q.Solids != 4 || q.Faces != 14 || q.EdgeUses != 56 || math.Abs(q.Volume-volume) > 1e-7 || math.Abs(q.Area-area) > 1e-7 {
				t.Fatal(q)
			}
			for i, want := range [6]float64{-10, -22, -2, 25, 25, 12} {
				if math.Abs(q.Bounds[i]-want) > 2e-7 {
					t.Fatal(q.Bounds)
				}
			}
			for i, want := range [3]float64{(-9*52 + 24*12*math.Pi*math.Pi + 1.5*20*math.Pi) / area, (-2.5*52 + 23*12*math.Pi*math.Pi - 20*20*math.Pi) / area, (5*12*math.Pi*math.Pi + 10*20*math.Pi) / area} {
				if math.Abs(q.SurfaceCenter[i]-want) > 1e-7 {
					t.Fatal("centroid", q.SurfaceCenter)
				}
			}
		}
	}
}

func TestIndependentAnalyticAssemblyReject(t *testing.T) {
	slowtest.Skip(t)
	ctx := context.Background()
	raw, e := os.ReadFile("testdata/independent-analytic-assembly.step")
	if e != nil {
		t.Fatal(e)
	}
	a, e := ReadIndependentAnalyticAssembly(ctx, bytes.NewReader(raw), Limits{}, 1e-9)
	if e != nil {
		t.Fatal(e)
	}
	var cylinder, torus IndependentExactMaterial
	for _, p := range a.Products {
		if p.Cylinder != nil {
			cylinder = p
		}
		if p.Torus != nil {
			torus = p
		}
	}
	for _, kind := range []string{"radius", "edge-sense", "face-sense", "borrow", "duplicate-family", "orphan", "pose", "nested", "units", "cycle"} {
		f, e := Parse(bytes.NewReader(raw), Limits{})
		if e != nil {
			t.Fatal(e)
		}
		switch kind {
		case "radius":
			for _, id := range cylinder.Source.Order {
				en := f.Entities[id]
				if len(en.Records) == 1 && en.Records[0].Type == "CYLINDRICAL_SURFACE" {
					en.Records[0].Args[2].Text = "2.000000000000001"
					f.Entities[id] = en
				}
			}
		case "edge-sense":
			id := cylinder.Cylinder.SourceEdges[0]
			en := f.Entities[id]
			en.Records[0].Args[4].Text = "F"
			f.Entities[id] = en
		case "face-sense":
			id := cylinder.Cylinder.SourceFaces[0]
			en := f.Entities[id]
			en.Records[0].Args[3].Text = "F"
			f.Entities[id] = en
		case "borrow":
			for _, id := range cylinder.Source.Order {
				en := f.Entities[id]
				if len(en.Records) == 1 && en.Records[0].Type == "EDGE_CURVE" {
					en.Records[0].Args[3].Ref = torus.Torus.SourceCircleIDs[0]
					f.Entities[id] = en
					break
				}
			}
		case "duplicate-family":
			en := f.Entities[cylinder.SourceRepresentationID]
			en.Records[0].Args[1].Items[1].Ref = torus.SourceBodyID
			f.Entities[cylinder.SourceRepresentationID] = en
		case "orphan":
			id := f.Order[len(f.Order)-1] + 1
			en := f.Entities[cylinder.Cylinder.SourceEdges[0]]
			en.ID = id
			f.Entities[id] = en
			f.Order = append(f.Order, id)
		case "pose", "nested", "cycle":
			for _, u := range a.Assembly.Occurrences {
				if u.Child == cylinder.SourceDefinitionID {
					en := f.Entities[u.ID]
					if kind == "pose" {
						en.Records[0].Args[4].Ref = torus.SourceDefinitionID
					} else if kind == "nested" {
						en.Records[0].Args[3].Ref = torus.SourceDefinitionID
					} else {
						en.Records[0].Args[4].Ref = a.Assembly.Roots[0]
					}
					f.Entities[u.ID] = en
				}
			}
		case "units":
			for _, id := range f.Order {
				en := f.Entities[id]
				for i, r := range en.Records {
					if r.Type == "SI_UNIT" && r.Args[1].Text == "RADIAN" {
						en.Records[i].Args[1].Text = "STERADIAN"
						f.Entities[id] = en
					}
				}
			}
		}
		b, e := mappedPlanarSourceBytes(f)
		if e != nil {
			t.Fatal(e)
		}
		if got, e := ReadIndependentAnalyticAssembly(ctx, bytes.NewReader(b), Limits{}, 1e-9); e == nil || len(got.Products) != 0 {
			t.Fatal(kind)
		}
	}
	var native bytes.Buffer
	if e = WriteIndependentAnalyticAssemblyJSON(ctx, &native, a); e != nil {
		t.Fatal(e)
	}
	for _, kind := range []string{"tag", "occurrence", "id", "frame", "rim", "native", "tolerance"} {
		var q independentTorusAssemblyEnvelope
		if e = json.Unmarshal(native.Bytes(), &q); e != nil {
			t.Fatal(e)
		}
		switch kind {
		case "tag":
			q.Format = independentTorusAssemblyNativeFormat
		case "occurrence":
			q.Assembly.Occurrences[3].Child = torus.SourceDefinitionID
		case "id":
			q.Members[2].DefinitionID = torus.SourceDefinitionID
		case "tolerance":
			q.Tolerance *= 2
		case "native":
			q.Members[2].Native = json.RawMessage(`{}`)
		case "frame", "rim":
			changed := false
			for i := range q.Members {
				var claim map[string]any
				if json.Unmarshal(q.Members[i].Claims, &claim) != nil {
					t.Fatal("claim")
				}
				if _, ok := claim["CylinderFrame"]; ok {
					if kind == "frame" {
						claim["CylinderFrame"] = [3][4]float64{}
					} else {
						material := claim["Material"].(map[string]any)
						c := material["Cylinder"].(map[string]any)
						c["SourceEdges"] = []int{1}
					}
					q.Members[i].Claims, _ = json.Marshal(claim)
					changed = true
					break
				}
			}
			if !changed {
				t.Fatal("mutation")
			}
		}
		b, _ := json.Marshal(q)
		if got, e := ReadIndependentAnalyticAssemblyJSON(ctx, bytes.NewReader(b), IndependentMaterialJSONLimits{}); e == nil || len(got.Products) != 0 {
			t.Fatal(kind)
		}
	}
	for _, l := range []IndependentMaterialJSONLimits{{MaxBytes: 1}, {Source: Limits{MaxSolids: 3}}, {Source: Limits{MaxFaces: 10}}, {Source: Limits{MaxDepth: 2}}} {
		if _, e := ReadIndependentAnalyticAssemblyJSON(ctx, bytes.NewReader(native.Bytes()), l); e == nil {
			t.Fatal("limits")
		}
	}
	cancel, c := context.WithCancel(ctx)
	c()
	if _, e := ReadIndependentAnalyticAssemblyJSON(cancel, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{}); e == nil {
		t.Fatal("cancel")
	}
	a.Assembly.Occurrences[3].Transform[1][3]++
	var bad bytes.Buffer
	if e = WriteIndependentAnalyticAssemblyJSON(ctx, &bad, a); e == nil || bad.Len() != 0 {
		t.Fatal("atomic stale")
	}
	m := independentAnalyticAssemblyModel(t)
	m.Products[3].Source = m.Products[2].Source
	if e = WriteIndependentAnalyticAssembly(ctx, &bad, m, Limits{}, 1e-9); e == nil || bad.Len() != 0 {
		t.Fatal("missing cylinder")
	}
}
func FuzzIndependentAnalyticAssembly(f *testing.F) {
	b, e := os.ReadFile("testdata/independent-analytic-assembly.step")
	if e != nil {
		f.Fatal(e)
	}
	f.Add(b)
	f.Fuzz(func(t *testing.T, b []byte) {
		if len(b) > 1<<20 {
			return
		}
		m, e := ReadIndependentAnalyticAssembly(context.Background(), bytes.NewReader(b), Limits{MaxBytes: 1 << 20, MaxEntities: 2048, MaxValues: 32768, MaxSolids: 4, MaxFaces: 20, MaxVertices: 100, MaxEdgeUses: 100, MaxDepth: 16}, 1e-9)
		if e != nil && len(m.Products) != 0 {
			t.Fatal("partial")
		}
	})
}
