func TestIndependentAnalyticAssemblyHalfCylinder(t *testing.T) {
	slowtest.Skip(t)
	ctx := context.Background()
	m := independentAnalyticAssemblyModel(t)
	raw, e := os.ReadFile("testdata/independent-cylinder-materials.step")
	if e != nil {
		t.Fatal(e)
	}
	c, e := ReadIndependentCylinderMaterials(ctx, bytes.NewReader(raw), Limits{}, 1e-9)
	if e != nil {
		t.Fatal(e)
	}
	found := false
	for _, p := range c.Members {
		if p.Cylinder != nil && p.Cylinder.Cells == 2 {
			m.Products[3].Source = p.Source
			found = true
			break
		}
	}
	if !found {
		t.Fatal("half source")
	}
	var out bytes.Buffer
	if e = WriteIndependentAnalyticAssembly(ctx, &out, m, Limits{}, 1e-9); e != nil {
		t.Fatal(e)
	}
	a, e := ReadIndependentAnalyticAssembly(ctx, bytes.NewReader(out.Bytes()), Limits{}, 1e-9)
	if e != nil {
		t.Fatal(e)
	}
	for _, p := range a.Products {
		if p.Cylinder != nil && p.Cylinder.Cells != 2 {
			t.Fatal("source cells lost")
		}
	}
}
