func TestRationalSpeedNonplanarSplineShellMapIdentity(t *testing.T) {
	ctx := context.Background()
	raw := rationalSpeedNonplanarRoofFixture(t)
	m, e := ReadRationalSpeedNonplanarSplineShellSource(ctx, bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	if len(m.ParameterMaps()) != 36 {
		t.Fatal("maps")
	}
	source, e := Parse(bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	var generated bytes.Buffer
	if e = WriteSplineShells(&generated, m.Model); e != nil {
		t.Fatal(e)
	}
	for _, ev := range m.ParameterMaps() {
		if ev.Ratio != "2" {
			t.Fatal("original speed", ev)
		}
		if ev.Dimension != 3 {
			continue
		}

		for _, n := range []int64{1, 2, 3} {
			tval := big.NewRat(n, 4)
			q := new(big.Rat).Quo(new(big.Rat).Mul(big.NewRat(2, 1), tval), new(big.Rat).Add(big.NewRat(1, 1), tval))
			// Evaluate the original rational model independently, then compose each
			// original owner UV at the same t and its unchanged carrier.
			for _, uv := range m.ParameterMaps() {
				if uv.Dimension != 2 || uv.EdgeID != ev.EdgeID {
					continue
				}
				var coords [2]*big.Rat
				for j := 0; j < 2; j++ {
					a, _ := new(big.Rat).SetString(uv.Poles[0][j])
					b, _ := new(big.Rat).SetString(uv.Poles[1][j])
					coords[j] = new(big.Rat).Add(a, new(big.Rat).Mul(q, new(big.Rat).Sub(b, a)))
				}
				surface, e := DecodeBSplineSurface(source, uv.SurfaceID, 64)
				if e != nil {
					t.Fatal(e)
				}
				patch, e := geom.NewSurfacePatch(surface.Geometry, geom.SurfacePatchOptions{})
				if e != nil {
					t.Fatal(e)
				}
				p, e := patch.EvaluateRational(ctx, coords[0], coords[1], geom.SurfacePatchEvaluationOptions{})
				if e != nil {
					t.Fatal(e)
				}
				var h [3][4]*big.Rat
				for i := 0; i <= ev.Degree; i++ {
					w, _ := new(big.Rat).SetString(ev.Weights[i])
					h[i][3] = w
					for j := 0; j < 3; j++ {
						x, _ := new(big.Rat).SetString(ev.Poles[i][j])
						h[i][j] = new(big.Rat).Mul(w, x)
					}
				}
				for level := ev.Degree; level > 0; level-- {
					for i := 0; i < level; i++ {
						for j := 0; j < 4; j++ {
							h[i][j] = new(big.Rat).Add(new(big.Rat).Mul(new(big.Rat).Sub(big.NewRat(1, 1), tval), h[i][j]), new(big.Rat).Mul(tval, h[i+1][j]))
						}
					}
				}
				for j := 0; j < 3; j++ {
					if new(big.Rat).Quo(h[0][j], h[0][3]).Cmp(p.Point[j]) != 0 {
						t.Fatal("source rational model and carrier lift disagree", ev.CurveID, uv.PCurveID, tval)
					}
				}
			}
		}
	}
	cp := m.ParameterMaps()
	cp[0].Ratio = "99"
	if m.ParameterMaps()[0].Ratio != "2" {
		t.Fatal("mutable maps")
	}
}

