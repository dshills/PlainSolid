func TestRationalSpeedNonplanarSplineShellOriginal(t *testing.T) {
	ctx := context.Background()
	raw := rationalSpeedNonplanarRoofFixture(t)
	if _, e := ReadSplineShells(bytes.NewReader(raw), Limits{}); e == nil {
		t.Fatal("original LINE-only gate widened")
	}
	if _, e := ReadNonplanarSplineShellSource(ctx, bytes.NewReader(raw), Limits{}); e == nil {
		t.Fatal("old exact polynomial reader widened")
	}
	m, e := ReadRationalSpeedNonplanarSplineShellSource(ctx, bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	if len(m.PCurves()) != 24 || len(m.SourceFaces()) != 6 || len(m.SourceEdges()) != 12 || m.OriginalSTEP() != string(raw) {
		t.Fatal("source roles")
	}
	mass, e := m.Model.Bodies[0].Solid.MassProperties(ctx, parametric.IntegrationOptions{})
	area := 12. + 56./3 + 15 + 3*math.Sqrt(5) + 12*math.Asinh(.5)
	if e != nil || math.Abs(mass.Volume-28) > 1e-10 || math.Abs(mass.Area-area) > 1e-7 || math.Abs(mass.Centroid.X-15./7) > 1e-10 || math.Abs(mass.Centroid.Z-83./70) > 1e-10 {
		t.Fatal(mass, e)
	}
	proof, e := m.Model.Bodies[0].Solid.ValidateEdgeAgreement(ctx, edgecheck.Options{})
	if e != nil || !proof.Complete {
		t.Fatal(e)
	}
	for _, u := range proof.Uses {
		if u.Report.SquaredUpperBound == nil || u.Report.SquaredUpperBound.Sign() != 0 {
			t.Fatal("nonzero continuous edge discrepancy")
		}
	}
	var native bytes.Buffer
	if e = WriteRationalSpeedNonplanarSplineShellSourceJSON(ctx, &native, m); e != nil {
		t.Fatal(e)
	}
	loaded, e := ReadRationalSpeedNonplanarSplineShellSourceJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	var again bytes.Buffer
	if e = WriteRationalSpeedNonplanarSplineShellSourceJSON(ctx, &again, loaded); e != nil || !bytes.Equal(native.Bytes(), again.Bytes()) {
		t.Fatal("native stability", e)
	}
	var q rationalSpeedNonplanarSplineShellEnvelope
	if e = json.Unmarshal(native.Bytes(), &q); e != nil {
		t.Fatal(e)
	}
	s, e := trimmed.ReadJSON(bytes.NewReader(q.Native), trimmed.JSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	p, e := s.ValidateSplineRectangleEmbedding(ctx, trimmed.SplineRectangleEmbeddingOptions{})
	if e != nil || !p.Complete {
		t.Fatal("native embedded material", e)
	}
	var source, generated bytes.Buffer
	if e = WriteRationalSpeedNonplanarSplineShellSource(ctx, &source, loaded, Limits{}); e != nil || !bytes.Equal(raw, source.Bytes()) {
		t.Fatal("source", e)
	}
	if e = WriteSplineShells(&generated, loaded.Model); e != nil {
		t.Fatal(e)
	}
	if _, e = ReadSplineShells(bytes.NewReader(generated.Bytes()), Limits{}); e != nil {
		t.Fatal("generated", e)
	}
	f, e := Parse(bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	for i, j := 0, len(f.Order)-1; i < j; i, j = i+1, j-1 {
		f.Order[i], f.Order[j] = f.Order[j], f.Order[i]
	}
	reordered, e := mappedPlanarSourceBytes(f)
	if e != nil {
		t.Fatal(e)
	}
	if _, e = ReadRationalSpeedNonplanarSplineShellSource(ctx, bytes.NewReader(reordered), Limits{}); e != nil {
		t.Fatal("record order", e)
	}
	cp := m.PCurves()
	cp[0].EdgeID++
	if cp[0].EdgeID == m.PCurves()[0].EdgeID {
		t.Fatal("mutable provenance")
	}
}
