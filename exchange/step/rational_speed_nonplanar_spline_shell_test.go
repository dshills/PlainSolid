func TestRationalSpeedNonplanarSplineShellLive(t *testing.T) {
	bin := os.Getenv("PLAINSOLID_OCCT_RATIONAL_SPEED_ROOF")
	if bin == "" {
		t.Skip("standalone OCCT helper")
	}
	for _, mode := range []string{"write", "write-half"} {
		t.Run(mode, func(t *testing.T) {
			ctx := context.Background()
			path := filepath.Join(t.TempDir(), "original.step")
			if b, e := exec.Command(bin, mode, path).CombinedOutput(); e != nil {
				t.Fatal(e, string(b))
			}
			raw, e := os.ReadFile(path)
			if e != nil {
				t.Fatal(e)
			}
			m, e := ReadRationalSpeedNonplanarSplineShellSource(ctx, bytes.NewReader(raw), Limits{})
			if e != nil {
				t.Fatal(e)
			}
			var native bytes.Buffer
			if e = WriteRationalSpeedNonplanarSplineShellSourceJSON(ctx, &native, m); e != nil {
				t.Fatal(e)
			}
			m, e = ReadRationalSpeedNonplanarSplineShellSourceJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{})
			if e != nil {
				t.Fatal(e)
			}
			for _, kind := range []string{"source", "generated"} {
				var out bytes.Buffer
				if kind == "source" {
					e = WriteRationalSpeedNonplanarSplineShellSource(ctx, &out, m, Limits{})
				} else {
					e = WriteSplineShells(&out, m.Model)
				}
				if e != nil {
					t.Fatal(e)
				}
				p := filepath.Join(t.TempDir(), kind+".step")
				os.WriteFile(p, out.Bytes(), 0600)
				b, e := exec.Command(bin, "read", p).CombinedOutput()
				if e != nil {
					t.Fatal(e, string(b))
				}
				var report struct {
					Volume, Area  float64
					Faces, Solids int
					Centroid      [3]float64
				}
				lines := bytes.Split(b, []byte("\n"))
				found := false
				for _, line := range lines {
					if json.Unmarshal(line, &report) == nil && report.Solids == 1 {
						found = true
						break
					}
				}
				if !found || math.Abs(report.Volume-28) > 1e-9 || math.Abs(report.Area-58.14941249988128) > 1e-7 || report.Faces != 6 || math.Abs(report.Centroid[2]-83./70) > 1e-8 {
					t.Fatal(kind, string(b))
				}
			}
		})
	}
}
