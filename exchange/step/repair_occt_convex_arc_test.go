func convexArcOriginal(t *testing.T) []byte {
	t.Helper()
	raw, e := os.ReadFile("testdata/occt-model-only-oblique-prism-fillet.step")
	if e != nil {
		t.Fatal(e)
	}
	return raw
}
func TestRepairOCCTConvexArcOriginal(t *testing.T) {
	raw := convexArcOriginal(t)
	ctx := context.Background()
	if _, e := ReadOCCTExactCircularLoopExtrusion(ctx, bytes.NewReader(raw), Limits{}); e == nil {
		t.Fatal("original must fail exact proof")
	}
	if _, e := ReadConvexArcExtrusion(bytes.NewReader(raw), Limits{}); e == nil {
		t.Fatal("canonical route must remain strict")
	}
	m, e := RepairOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{MaxDistance: 1e-12})
	if e != nil {
		t.Fatal(e)
	}
	if m.OriginalSTEP() != string(raw) || len(m.Repairs()) != 3 || len(m.AzimuthDirections()) != 3 {
		t.Fatal("source evidence")
	}
	want, _ := new(big.Rat).SetString("1.110223024625E-16")
	want.Mul(want, want)
	for _, q := range m.Repairs() {
		if q.SquaredDistance.Cmp(want) != 0 {
			t.Fatal(q)
		}
	}
	p := m.Provenance()
	if p.ProductID == 0 || p.Body == 0 || len(p.Walls) != 4 || len(p.Rims[0]) != 4 || len(p.Vertices[1]) != 4 {
		t.Fatal(p)
	}
	m.Repairs()[0].SquaredDistance.SetInt64(99)
	m.Repairs()[0].Original[0].SetInt64(99)
	p.Walls[0] = 0
	if m.Repairs()[0].SquaredDistance.Cmp(want) != 0 || m.Provenance().Walls[0] == 0 {
		t.Fatal("mutable evidence")
	}
	proof, e := m.Solid().ValidateEdgeAgreement(ctx, edgecheck.Options{})
	if e != nil || !proof.Complete {
		t.Fatal(e, proof)
	}
	for _, u := range proof.Uses {
		if u.Report.SquaredUpperBound.Sign() != 0 {
			t.Fatal("corrected native must sew exactly", u)
		}
	}
	var b bytes.Buffer
	if e = trimmed.WriteJSON(&b, m.Solid()); e != nil {
		t.Fatal(e)
	}
	reload, e := trimmed.ReadJSON(&b, trimmed.JSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	props, e := reload.MassProperties(ctx, parametric.IntegrationOptions{})
	r := 5.0 / 16
	w := math.Atan2(3, -4)
	area := 6 - r*r*(3-w/2)
	perimeter := 12 - 6*r + r*w
	if e != nil || math.Abs(props.Volume-5*area) > 1e-8 || math.Abs(props.Area-(2*area+5*perimeter)) > 1e-8 {
		t.Fatal(props, e)
	}
	corrected, e := ReadOCCTExactCircularLoopExtrusion(ctx, bytes.NewBufferString(m.CorrectedSTEP()), Limits{})
	if e != nil || corrected.Body != p.Body {
		t.Fatal(e)
	}
	var generated bytes.Buffer
	if e = WriteExactCircularLoopExtrusion(ctx, &generated, m.Descriptor()); e != nil {
		t.Fatal(e)
	}
	if _, e = ReadExactCircularLoopExtrusion(ctx, bytes.NewReader(generated.Bytes()), Limits{}); e != nil {
		t.Fatal(e)
	}
}
func TestRepairOCCTConvexArcReject(t *testing.T) {
	raw := convexArcOriginal(t)
	ctx := context.Background()
	for _, tol := range []float64{0, -1, math.NaN(), math.Inf(1), 1e-18, 1e-3} {
		if m, e := RepairOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{tol}); e == nil || m.OriginalSTEP() != "" {
			t.Fatal("tolerance", tol, e)
		}
	}
	mutations := map[string]func(*File){
		"radius": func(f *File) {
			for _, id := range f.Order {
				r := &f.Entities[id].Records[0]
				if r.Type == "CYLINDRICAL_SURFACE" {
					r.Args[2].Text = "0.312500000000001"
					return
				}
			}
		},
		"circle": func(f *File) {
			for _, id := range f.Order {
				r := &f.Entities[id].Records[0]
				if r.Type == "CIRCLE" {
					r.Args[2].Text = "0.312500000000001"
					return
				}
			}
		},
		"edge sense": func(f *File) {
			for _, id := range f.Order {
				r := &f.Entities[id].Records[0]
				if r.Type == "EDGE_CURVE" {
					r.Args[4].Text = "F"
					return
				}
			}
		},
		"wrong owner": func(f *File) {
			for _, id := range f.Order {
				r := &f.Entities[id].Records[0]
				if r.Type == "ORIENTED_EDGE" {
					r.Args[3].Ref = id
					return
				}
			}
		},
		"line direction": func(f *File) {
			for _, id := range f.Order {
				r := f.Entities[id].Records[0]
				if r.Type == "LINE" {
					v := f.Entities[r.Args[2].Ref].Records[0]
					d := &f.Entities[v.Args[1].Ref].Records[0]
					d.Args[1].Items[2].Text = "1."
					return
				}
			}
		},
		"unequal endpoint shift": func(f *File) {
			for _, id := range f.Order {
				r := &f.Entities[id].Records[0]
				if r.Type == "CARTESIAN_POINT" && len(r.Args[1].Items) == 3 && r.Args[1].Items[1].Text == "-1.110223024625E-16" {
					r.Args[1].Items[1].Text = "-2.E-16"
					return
				}
			}
		},
		"pcurve": func(f *File) {
			id := f.Order[len(f.Order)-1] + 1
			f.Entities[id] = Entity{ID: id, Records: []Record{{Type: "PCURVE", Args: []Value{{Kind: String}, {Kind: Reference, Ref: 1}, {Kind: Reference, Ref: 1}}}}}
			f.Order = append(f.Order, id)
		},
	}
	for name, mutate := range mutations {
		t.Run(name, func(t *testing.T) {
			f, e := Parse(bytes.NewReader(raw), Limits{})
			if e != nil {
				t.Fatal(e)
			}
			mutate(f)
			b, e := mappedPlanarSourceBytes(f)
			if e != nil {
				t.Fatal(e)
			}
			m, e := RepairOCCTConvexArcExtrusion(ctx, bytes.NewReader(b), Limits{}, ConvexArcRepairOptions{1e-12})
			if e == nil || m.OriginalSTEP() != "" {
				t.Fatal("accepted", e)
			}
		})
	}
	canceled, cancel := context.WithCancel(ctx)
	cancel()
	if _, e := RepairOCCTConvexArcExtrusion(canceled, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12}); e != context.Canceled {
		t.Fatal(e)
	}
	if _, e := RepairOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{MaxBytes: 64}, ConvexArcRepairOptions{1e-12}); e == nil {
		t.Fatal("limit")
	}
}
func TestRepairOCCTConvexArcLive(t *testing.T) {
	bin := os.Getenv("PLAINSOLID_OCCT_CONVEX_ARC_ORIGINAL")
	if bin == "" {
		t.Skip("set pinned independent author/read comparator")
	}
	dir := t.TempDir()
	source := filepath.Join(dir, "original.step")
	if out, e := exec.Command(bin, "write", source).CombinedOutput(); e != nil {
		t.Fatal(e, string(out))
	}
	raw, e := os.ReadFile(source)
	if e != nil {
		t.Fatal(e)
	}
	m, e := RepairOCCTConvexArcExtrusion(context.Background(), bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12})
	if e != nil {
		t.Fatal(e)
	}
	var generated bytes.Buffer
	if e = WriteExactCircularLoopExtrusion(context.Background(), &generated, m.Descriptor()); e != nil {
		t.Fatal(e)
	}
	for name, data := range map[string][]byte{"original": raw, "corrected": []byte(m.CorrectedSTEP()), "generated": generated.Bytes()} {
		path := filepath.Join(dir, name+".step")
		if e = os.WriteFile(path, data, 0600); e != nil {
			t.Fatal(e)
		}
		out, e := exec.Command(bin, "read", path).CombinedOutput()
		if e != nil {
			t.Fatal(name, e, string(out))
		}
		at := bytes.LastIndex(out, []byte("{\"Volume\""))
		if at < 0 {
			t.Fatal(string(out))
		}
		var q struct {
			Volume, Area  float64
			Faces, Solids int
		}
		if e = json.Unmarshal(bytes.TrimSpace(out[at:]), &q); e != nil {
			t.Fatal(e)
		}
		r := 5.0 / 16
		w := math.Atan2(3, -4)
		a := 6 - r*r*(3-w/2)
		p := 12 - 6*r + r*w
		if q.Faces != 6 || q.Solids != 1 || math.Abs(q.Volume-5*a) > 1e-8 || math.Abs(q.Area-(2*a+5*p)) > 1e-8 {
			t.Fatal(name, q)
		}
	}
}
func FuzzRepairOCCTConvexArc(f *testing.F) {
	raw, e := os.ReadFile("testdata/occt-model-only-oblique-prism-fillet.step")
	if e != nil {
		f.Fatal(e)
	}
	f.Add(raw)
	f.Add([]byte("ISO-10303-21;"))
	f.Fuzz(func(t *testing.T, raw []byte) {
		if len(raw) > 1<<20 {
			t.Skip()
		}
		m, e := RepairOCCTConvexArcExtrusion(context.Background(), bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12})
		if e != nil && m.OriginalSTEP() != "" {
			t.Fatal("partial failure")
		}
	})
}
