func exactLoopNativeFixture(t testing.TB, vendor, negative bool) (OCCTExactCircularLoopExtrusion, []byte) {
	t.Helper()
	ctx := context.Background()
	var m OCCTExactCircularLoopExtrusion
	var e error
	if vendor {
		m, e = ReadOCCTExactCircularLoopExtrusion(ctx, bytes.NewReader(occtLoopFixture(t)), Limits{})
	} else {
		m.ExactCircularLoopExtrusionProduct, e = ReadExactCircularLoopExtrusion(ctx, bytes.NewReader(exactLoopSTEPBytes(t, negative)), Limits{})
	}
	if e != nil {
		t.Fatal(e)
	}
	var b bytes.Buffer
	if e = writeExactLoopNative(ctx, &b, m.ExactCircularLoopExtrusionProduct, m.Product, vendor); e != nil {
		t.Fatal(e)
	}
	return m, b.Bytes()
}
func TestExactCircularLoopNative(t *testing.T) {
	slowtest.Skip(t)
	ctx := context.Background()
	for _, c := range []struct{ vendor, negative bool }{{false, false}, {false, true}, {true, false}} {
		m, b := exactLoopNativeFixture(t, c.vendor, c.negative)
		proof, e := readExactLoopNative(ctx, bytes.NewReader(b), IndependentMaterialJSONLimits{}, c.vendor)
		if e != nil {
			t.Fatal(e)
		}
		var next bytes.Buffer
		if e = writeExactLoopNative(ctx, &next, proof.ExactCircularLoopExtrusionProduct, proof.Product, c.vendor); e != nil || !bytes.Equal(b, next.Bytes()) {
			t.Fatal("unstable native", e)
		}
		if proof.Descriptor.Height != m.Descriptor.Height || proof.Body != m.Body || proof.Caps != m.Caps {
			t.Fatal("lost signed/source roles")
		}
		if _, e = readExactLoopNative(ctx, bytes.NewReader(b), IndependentMaterialJSONLimits{}, !c.vendor); e == nil {
			t.Fatal("cross-tag accepted")
		}
		var source, generated bytes.Buffer
		if c.vendor {
			e = WriteOCCTExactCircularLoopSource(ctx, &source, proof.Source, Limits{})
		} else {
			e = WriteExactCircularLoopExtrusionSource(ctx, &source, proof.Source, Limits{})
		}
		if e != nil {
			t.Fatal(e)
		}
		if _, e = exactLoopNativeReproof(ctx, source.String(), Limits{}, c.vendor); e != nil {
			t.Fatal(e)
		}
		if e = WriteExactCircularLoopExtrusion(ctx, &generated, proof.Descriptor); e != nil {
			t.Fatal(e)
		}
		if _, e = ReadExactCircularLoopExtrusion(ctx, &generated, Limits{}); e != nil {
			t.Fatal(e)
		}
		if e = writeExactLoopNative(ctx, sideDiskShortWriter{}, m.ExactCircularLoopExtrusionProduct, m.Product, c.vendor); !errors.Is(e, io.ErrShortWrite) {
			t.Fatal(e)
		}
	}
}
func TestExactCircularLoopNativeCorruption(t *testing.T) {
	slowtest.Skip(t)
	ctx := context.Background()
	for _, vendor := range []bool{false, true} {
		m, b := exactLoopNativeFixture(t, vendor, !vendor)
		for i, mutate := range []func(*exactLoopNativeEnvelope){func(q *exactLoopNativeEnvelope) { q.Version++ }, func(q *exactLoopNativeEnvelope) { q.Body++ }, func(q *exactLoopNativeEnvelope) { q.Rims[0][0]++ }, func(q *exactLoopNativeEnvelope) { q.Vertices[1][0]++ }, func(q *exactLoopNativeEnvelope) { q.Caps[0], q.Caps[1] = q.Caps[1], q.Caps[0] }, func(q *exactLoopNativeEnvelope) { q.Recipe.Height = -q.Recipe.Height }, func(q *exactLoopNativeEnvelope) { q.Recipe.Frame[0][3]++ }, func(q *exactLoopNativeEnvelope) { q.Recipe.Segments[1].Radius = 1 }, func(q *exactLoopNativeEnvelope) { q.Recipe.LengthUnit = 1 }, func(q *exactLoopNativeEnvelope) { q.Product.Name = "forged" }, func(q *exactLoopNativeEnvelope) { q.Native = json.RawMessage(`{}`) }, func(q *exactLoopNativeEnvelope) {
			q.Source = string(bytes.Replace([]byte(q.Source), []byte("0.625"), []byte("0.626"), 1))
		}} {
			var q exactLoopNativeEnvelope
			if e := json.Unmarshal(b, &q); e != nil {
				t.Fatal(e)
			}
			mutate(&q)
			bad, _ := json.Marshal(q)
			got, e := readExactLoopNative(ctx, bytes.NewReader(bad), IndependentMaterialJSONLimits{}, vendor)
			if e == nil || got.Source != nil {
				t.Fatal("accepted corruption", vendor, i)
			}
		}
		for _, bad := range [][]byte{append(append([]byte(nil), b...), []byte(`{}`)...), bytes.Replace(b, []byte(`"Version":1`), []byte(`"Unknown":true,"Version":1`), 1)} {
			if _, e := readExactLoopNative(ctx, bytes.NewReader(bad), IndependentMaterialJSONLimits{}, vendor); e == nil {
				t.Fatal("malformed JSON")
			}
		}
		for _, l := range []IndependentMaterialJSONLimits{{MaxBytes: 20}, {MaxBytes: 9 << 20}, {Source: Limits{MaxEntities: 10}}, {Source: Limits{MaxFaces: 2}}} {
			if _, e := readExactLoopNative(ctx, bytes.NewReader(b), l, vendor); e == nil {
				t.Fatal("limit")
			}
		}
		c, cancel := context.WithCancel(ctx)
		cancel()
		if _, e := readExactLoopNative(c, bytes.NewReader(b), IndependentMaterialJSONLimits{}, vendor); !errors.Is(e, context.Canceled) {
			t.Fatal(e)
		}
		during, stop := context.WithCancel(ctx)
		reader := &occurrenceCancelReader{Reader: bytes.NewReader(b), cancel: stop}
		if _, e := readExactLoopNative(during, reader, IndependentMaterialJSONLimits{}, vendor); !errors.Is(e, context.Canceled) {
			t.Fatal("read cancellation", e)
		}
		m.VerticalEdges[0]++
		var out bytes.Buffer
		if e := writeExactLoopNative(ctx, &out, m.ExactCircularLoopExtrusionProduct, m.Product, vendor); e == nil || out.Len() != 0 {
			t.Fatal("non-atomic stale write")
		}
	}
}
func FuzzExactCircularLoopNative(f *testing.F) {
	_, a := exactLoopNativeFixture(f, false, true)
	_, b := exactLoopNativeFixture(f, true, false)
	f.Add(a, false)
	f.Add(b, true)
	f.Add([]byte(`{}`), false)
	f.Fuzz(func(t *testing.T, b []byte, vendor bool) {
		if len(b) > 1<<20 {
			t.Skip()
		}
		m, e := readExactLoopNative(context.Background(), bytes.NewReader(b), IndependentMaterialJSONLimits{MaxBytes: 1 << 20}, vendor)
		if e != nil && m.Source != nil {
			t.Fatal("partial result")
		}
	})
}
