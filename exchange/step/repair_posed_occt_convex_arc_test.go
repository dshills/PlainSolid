func posedConvexArcOriginal(t *testing.T) []byte {
	t.Helper()
	raw, e := os.ReadFile("testdata/occt-model-only-posed-oblique-prism-fillet.step")
	if e != nil {
		t.Fatal(e)
	}
	return raw
}
func TestRepairPosedOCCTConvexArc(t *testing.T) {
	raw := posedConvexArcOriginal(t)
	ctx := context.Background()
	if _, e := RepairOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12}); e == nil {
		t.Fatal("unposed stays strict")
	}
	if _, e := ReadPosedOCCTExactCircularLoopExtrusion(ctx, bytes.NewReader(raw), Limits{}); e == nil {
		t.Fatal("exact stays strict")
	}
	m, e := RepairPosedOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12})
	if e != nil {
		t.Fatal(e)
	}
	if m.OriginalSTEP() != string(raw) || len(m.Repairs()) != 3 || m.Descriptor().Frame.ZAxis() != (geom.Vec3{X: 1}) || m.Descriptor().Frame.Origin() != (geom.Vec3{X: 2}) || m.ReferenceCircleID() == 0 {
		t.Fatal("world binding", m.Descriptor())
	}
	bound, _ := new(big.Rat).SetString("1.110223024625E-16")
	bound.Mul(bound, bound)
	for _, q := range m.Repairs() {
		if q.SquaredDistance.Cmp(bound) != 0 || q.Original[2].Sign() >= 0 || q.Repaired[2].Sign() != 0 {
			t.Fatal("original world evidence", q)
		}
	}
	var native bytes.Buffer
	if e = trimmed.WriteJSON(&native, m.Solid()); e != nil {
		t.Fatal(e)
	}
	reload, e := trimmed.ReadJSON(&native, trimmed.JSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	proof, e := reload.ValidateEdgeAgreement(ctx, edgecheck.Options{})
	if e != nil || !proof.Complete {
		t.Fatal(e)
	}
	for _, u := range proof.Uses {
		if u.Report.SquaredUpperBound.Sign() != 0 {
			t.Fatal("exact native sew")
		}
	}
	corrected, e := ReadPosedOCCTExactCircularLoopExtrusion(ctx, bytes.NewBufferString(m.CorrectedSTEP()), Limits{})
	if e != nil || corrected.Body != m.Provenance().Body {
		t.Fatal(e)
	}
	var generated bytes.Buffer
	if e = WriteExactCircularLoopExtrusion(ctx, &generated, m.Descriptor()); e != nil {
		t.Fatal(e)
	}
	if _, e = ReadExactCircularLoopExtrusion(ctx, bytes.NewReader(generated.Bytes()), Limits{}); e != nil {
		t.Fatal(e)
	}
	r := m.Repairs()
	r[0].Original[0].SetInt64(99)
	if m.Repairs()[0].Original[0].Cmp(big.NewRat(99, 1)) == 0 {
		t.Fatal("alias")
	}
}
func TestRepairPosedOCCTConvexArcReject(t *testing.T) {
	raw := posedConvexArcOriginal(t)
	ctx := context.Background()
	for _, name := range []string{"noncardinal circle", "disagreeing cylinder", "metadata pose", "wrong owner"} {
		t.Run(name, func(t *testing.T) {
			f, e := Parse(bytes.NewReader(raw), Limits{})
			if e != nil {
				t.Fatal(e)
			}
			for _, id := range f.Order {
				r := f.Entities[id].Records[0]
				switch name {
				case "noncardinal circle":
					if r.Type == "CIRCLE" {
						frame := f.Entities[r.Args[1].Ref].Records[0]
						d := &f.Entities[frame.Args[2].Ref].Records[0]
						d.Args[1].Items = []Value{{Kind: Number, Text: "0.6"}, {Kind: Number, Text: "0.8"}, {Kind: Number, Text: "0."}}
						goto changed
					}
				case "disagreeing cylinder":
					if r.Type == "CYLINDRICAL_SURFACE" {
						frame := f.Entities[r.Args[1].Ref].Records[0]
						d := &f.Entities[frame.Args[2].Ref].Records[0]
						d.Args[1].Items = []Value{{Kind: Number, Text: "-1."}, {Kind: Number, Text: "0."}, {Kind: Number, Text: "0."}}
						goto changed
					}
				case "metadata pose":
					if r.Type == "ADVANCED_BREP_SHAPE_REPRESENTATION" {
						frame := f.Entities[r.Args[1].Items[0].Ref].Records[0]
						p := &f.Entities[frame.Args[1].Ref].Records[0]
						p.Args[1].Items[0].Text = "1."
						goto changed
					}
				case "wrong owner":
					if r.Type == "ORIENTED_EDGE" {
						f.Entities[id].Records[0].Args[3].Ref = id
						goto changed
					}
				}
			}
		changed:
			b, e := mappedPlanarSourceBytes(f)
			if e != nil {
				t.Fatal(e)
			}
			m, e := RepairPosedOCCTConvexArcExtrusion(ctx, bytes.NewReader(b), Limits{}, ConvexArcRepairOptions{1e-12})
			if e == nil || m.OriginalSTEP() != "" {
				t.Fatal("accepted", e)
			}
		})
	}
	canceled, cancel := context.WithCancel(ctx)
	cancel()
	if _, e := RepairPosedOCCTConvexArcExtrusion(canceled, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12}); e != context.Canceled {
		t.Fatal(e)
	}
	for _, o := range []ConvexArcRepairOptions{{0}, {1e-18}} {
		if _, e := RepairPosedOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, o); e == nil {
			t.Fatal("tolerance")
		}
	}
	if _, e := RepairPosedOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{MaxBytes: 64}, ConvexArcRepairOptions{1e-12}); e == nil {
		t.Fatal("limit")
	}
}
func TestRepairPosedOCCTConvexArcLive(t *testing.T) {
	bin := os.Getenv("PLAINSOLID_OCCT_CONVEX_ARC_ORIGINAL")
	if bin == "" {
		t.Skip("set pinned independent author/read comparator")
	}
	ctx := context.Background()
	for _, mode := range []string{"write-x", "write-minus-x", "write-translated"} {
		t.Run(mode, func(t *testing.T) {
			dir := t.TempDir()
			path := filepath.Join(dir, "source.step")
			if out, e := exec.Command(bin, mode, path).CombinedOutput(); e != nil {
				t.Fatal(e, string(out))
			}
			raw, e := os.ReadFile(path)
			if e != nil {
				t.Fatal(e)
			}
			m, e := RepairPosedOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12})
			if e != nil {
				t.Fatal(e)
			}
			if len(m.Repairs()) != 3 {
				t.Fatal("genuine posed residuals", m.Repairs())
			}
			props, e := m.Solid().MassProperties(ctx, parametric.IntegrationOptions{})
			if e != nil {
				t.Fatal(e)
			}
			world := m.Descriptor().Frame.ToWorld(props.Centroid)
			var generated bytes.Buffer
			if e = WriteExactCircularLoopExtrusion(ctx, &generated, m.Descriptor()); e != nil {
				t.Fatal(e)
			}
			for name, data := range map[string][]byte{"original": raw, "corrected": []byte(m.CorrectedSTEP()), "generated": generated.Bytes()} {
				path := filepath.Join(dir, name+".step")
				if e = os.WriteFile(path, data, 0600); e != nil {
					t.Fatal(e)
				}
				out, e := exec.Command(bin, "read", path).CombinedOutput()
				if e != nil {
					t.Fatal(name, e, string(out))
				}
				at := bytes.LastIndex(out, []byte("{\"Volume\""))
				if at < 0 {
					t.Fatal(string(out))
				}
				var q struct {
					Volume, Area  float64
					Faces, Solids int
					Centroid      [3]float64
				}
				if e = json.Unmarshal(bytes.TrimSpace(out[at:]), &q); e != nil {
					t.Fatal(e)
				}
				if q.Faces != 6 || q.Solids != 1 || math.Abs(q.Volume-props.Volume) > 1e-8 || math.Abs(q.Area-props.Area) > 1e-8 || world.Distance(geom.Vec3{X: q.Centroid[0], Y: q.Centroid[1], Z: q.Centroid[2]}) > 1e-8 {
					t.Fatal(name, q, props, world)
				}
			}
		})
	}
}
func FuzzRepairPosedOCCTConvexArc(f *testing.F) {
	raw, e := os.ReadFile("testdata/occt-model-only-posed-oblique-prism-fillet.step")
	if e != nil {
		f.Fatal(e)
	}
	f.Add(raw)
	f.Add([]byte("ISO-10303-21;"))
	f.Fuzz(func(t *testing.T, raw []byte) {
		if len(raw) > 1<<20 {
			t.Skip()
		}
		m, e := RepairPosedOCCTConvexArcExtrusion(context.Background(), bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12})
		if e != nil && m.OriginalSTEP() != "" {
			t.Fatal("partial failure")
		}
	})
}

// The second actual OCCT fillet has an oppositely parameterized model circle,
// not merely an extra copy of the first cylinder's graph.
func TestRepairOCCTGroupedFilletsRemainExplicitlyUnsupported(t *testing.T) {
	raw, e := os.ReadFile("testdata/occt-model-only-two-oblique-prism-fillets.step")
	if e != nil {
		t.Fatal(e)
	}
	f, e := Parse(bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	cylinders, negativeCircles := 0, 0
	for _, id := range f.Order {
		r := f.Entities[id].Records[0]
		if r.Type == "CYLINDRICAL_SURFACE" {
			cylinders++
		}
		if r.Type == "CIRCLE" {
			_, z, _, e := occtLoopFrame(f, r.Args[1].Ref)
			if e != nil {
				t.Fatal(e)
			}
			if z[2].Sign() < 0 {
				negativeCircles++
			}
		}
	}
	if cylinders != 2 || negativeCircles != 2 {
		t.Fatal("actual distinct orientation", cylinders, negativeCircles)
	}
	if _, e = RepairOCCTConvexArcExtrusion(context.Background(), bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12}); e == nil {
		t.Fatal("single-fillet scope")
	}
	if _, e = RepairPosedOCCTConvexArcExtrusion(context.Background(), bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12}); e == nil {
		t.Fatal("posed scope")
	}
	bin := os.Getenv("PLAINSOLID_OCCT_CONVEX_ARC_ORIGINAL")
	if bin == "" {
		return
	}
	for _, mode := range []string{"write-both", "write-both-x"} {
		path := filepath.Join(t.TempDir(), "both.step")
		out, e := exec.Command(bin, mode, path).CombinedOutput()
		if e != nil {
			t.Fatal(e, string(out))
		}
		at := bytes.LastIndex(out, []byte("{\"Volume\""))
		if at < 0 {
			t.Fatal(string(out))
		}
		var q struct {
			Volume, Area  float64
			Faces, Solids int
		}
		if e = json.Unmarshal(bytes.TrimSpace(out[at:]), &q); e != nil {
			t.Fatal(e)
		}
		if q.Faces != 7 || q.Solids != 1 || math.Abs(q.Volume-29.077978807115535) > 1e-9 || math.Abs(q.Area-65.62295497008438) > 1e-9 {
			t.Fatal(q)
		}
		source, e := os.ReadFile(path)
		if e != nil {
			t.Fatal(e)
		}
		if _, e = RepairPosedOCCTConvexArcExtrusion(context.Background(), bytes.NewReader(source), Limits{}, ConvexArcRepairOptions{1e-12}); e == nil {
			t.Fatal("not silently widened")
		}
	}
}
