func TestRepairGroupedOCCTConvexArc(t *testing.T) {
	t.Parallel()
	raw := groupedConvexArcOriginal(t)
	ctx := context.Background()
	m, e := RepairGroupedOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12})
	if e != nil {
		t.Fatal(e)
	}
	if len(m.Repairs()) != 9 || len(m.Reversals()) != 2 || len(m.Tangencies()) != 8 || m.OriginalSTEP() != string(raw) {
		t.Fatal("source evidence")
	}
	counts := map[int64]int{}
	for _, q := range m.Tangencies() {
		counts[q.CylinderFaceID]++
		if q.CapFaceID == 0 || q.PlaneFaceID == 0 || q.VertexID == 0 {
			t.Fatal(q)
		}
	}
	if len(counts) != 2 {
		t.Fatal(counts)
	}
	for _, n := range counts {
		if n != 4 {
			t.Fatal(counts)
		}
	}
	before, e := Parse(bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	after, e := Parse(bytes.NewBufferString(m.CorrectedSTEP()), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	for _, q := range m.Reversals() {
		a, _ := simple(before, q.EdgeID, "EDGE_CURVE", 5)
		b, _ := simple(after, q.EdgeID, "EDGE_CURVE", 5)
		if a.Args[1].Ref != q.OriginalStart || a.Args[2].Ref != q.OriginalEnd || b.Args[1].Ref != q.OriginalEnd || b.Args[2].Ref != q.OriginalStart {
			t.Fatal(q)
		}
		for _, id := range q.OrientedUseIDs {
			u, _ := simple(before, id, "ORIENTED_EDGE", 5)
			v, _ := simple(after, id, "ORIENTED_EDGE", 5)
			a, _ := boolean(u.Args[4])
			b, _ := boolean(v.Args[4])
			if a == b {
				t.Fatal("paired coedge reversal", q)
			}
		}
	}
	proof, e := m.Solid().ValidateEdgeAgreement(ctx, edgecheck.Options{})
	if e != nil || !proof.Complete {
		t.Fatal(e)
	}
	for _, u := range proof.Uses {
		if u.Report.SquaredUpperBound.Sign() != 0 {
			t.Fatal("exact sewn geometry")
		}
	}
	var native bytes.Buffer
	if e = trimmed.WriteJSON(&native, m.Solid()); e != nil {
		t.Fatal(e)
	}
	reload, e := trimmed.ReadJSON(&native, trimmed.JSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	props, e := reload.MassProperties(ctx, parametric.IntegrationOptions{})
	r := 5.0 / 16
	w := math.Atan2(3, -4)
	a := 6 - r*r*(3-w/2) - .25*.25*(1-math.Pi/4)
	p := 12 - 6*r + r*w + .25*(math.Pi/2-2)
	if e != nil || math.Abs(props.Volume-5*a) > 1e-8 || math.Abs(props.Area-(2*a+5*p)) > 1e-8 {
		t.Fatal(props, e)
	}
	var generated bytes.Buffer
	if e = WriteExactCircularLoopExtrusion(ctx, &generated, m.Descriptor()); e != nil {
		t.Fatal(e)
	}
	if _, e = ReadExactCircularLoopExtrusion(ctx, bytes.NewReader(generated.Bytes()), Limits{}); e != nil {
		t.Fatal(e)
	}
	if _, e = ReadOCCTExactCircularLoopExtrusion(ctx, bytes.NewBufferString(m.CorrectedSTEP()), Limits{}); e != nil {
		t.Fatal(e)
	}
	q := m.Tangencies()
	q[0].Point[0].SetInt64(99)
	m.Reversals()[0].EdgeID = 0
	if m.Tangencies()[0].Point[0].String() == "99/1" || m.Reversals()[0].EdgeID == 0 {
		t.Fatal("mutable evidence")
	}
}
func TestRepairGroupedOCCTConvexArcReject(t *testing.T) {
	t.Parallel()
	raw := groupedConvexArcOriginal(t)
	ctx := context.Background()
	base, e := RepairGroupedOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12})
	if e != nil {
		t.Fatal(e)
	}
	rev := base.Reversals()[0]
	mutations := map[string]func(*File){
		"axis only":      func(f *File) { r := &f.Entities[rev.AxisDirectionID].Records[0]; r.Args[1].Items[2].Text = "1." },
		"endpoints only": func(f *File) { r := &f.Entities[rev.EdgeID].Records[0]; r.Args[1], r.Args[2] = r.Args[2], r.Args[1] },
		"one coedge": func(f *File) {
			r := &f.Entities[rev.OrientedUseIDs[0]].Records[0]
			b, _ := boolean(r.Args[4])
			r.Args[4].Text = "T"
			if b {
				r.Args[4].Text = "F"
			}
		},
		"complement with closed topology": func(f *File) {
			r := &f.Entities[rev.EdgeID].Records[0]
			r.Args[1], r.Args[2] = r.Args[2], r.Args[1]
			for _, id := range rev.OrientedUseIDs {
				u := &f.Entities[id].Records[0]
				b, _ := boolean(u.Args[4])
				u.Args[4].Text = "T"
				if b {
					u.Args[4].Text = "F"
				}
			}
		},
		"same sense": func(f *File) { f.Entities[rev.EdgeID].Records[0].Args[4].Text = "F" },
		"shared axis": func(f *File) {
			other := base.Reversals()[1]
			c := f.Entities[other.CircleID].Records[0]
			f.Entities[c.Args[1].Ref].Records[0].Args[2].Ref = rev.AxisDirectionID
		},
		"wrong cylinder": func(f *File) {
			ids := map[int64]bool{}
			var faces []int64
			for _, q := range base.Tangencies() {
				if !ids[q.CylinderFaceID] {
					ids[q.CylinderFaceID] = true
					faces = append(faces, q.CylinderFaceID)
				}
			}
			a := f.Entities[faces[0]].Records[0]
			b := &f.Entities[faces[1]].Records[0]
			b.Args[2].Ref = a.Args[2].Ref
		},
	}
	for name, mutate := range mutations {
		t.Run(name, func(t *testing.T) {
			f, e := Parse(bytes.NewReader(raw), Limits{})
			if e != nil {
				t.Fatal(e)
			}
			mutate(f)
			b, e := mappedPlanarSourceBytes(f)
			if e != nil {
				t.Fatal(e)
			}
			m, e := RepairGroupedOCCTConvexArcExtrusion(ctx, bytes.NewReader(b), Limits{}, ConvexArcRepairOptions{1e-12})
			if e == nil || m.OriginalSTEP() != "" {
				t.Fatal("accepted", e)
			}
		})
	}
	if _, e = RepairGroupedOCCTConvexArcExtrusion(ctx, bytes.NewReader(convexArcOriginal(t)), Limits{}, ConvexArcRepairOptions{1e-12}); e == nil {
		t.Fatal("group mode must require two")
	}
	if _, e = RepairGroupedOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-18}); e == nil {
		t.Fatal("insufficient tolerance")
	}
	c, cancel := context.WithCancel(ctx)
	cancel()
	if _, e = RepairGroupedOCCTConvexArcExtrusion(c, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12}); e != context.Canceled {
		t.Fatal(e)
	}
	if _, e = RepairGroupedOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{MaxBytes: 64}, ConvexArcRepairOptions{1e-12}); e == nil {
		t.Fatal("limit")
	}
}
func TestRepairGroupedOCCTConvexArcLive(t *testing.T) {
	t.Parallel()
	bin := os.Getenv("PLAINSOLID_OCCT_CONVEX_ARC_ORIGINAL")
	if bin == "" {
		t.Skip("set pinned independent author/read comparator")
	}
	ctx := context.Background()
	for _, mode := range []string{"write-both", "write-both-x"} {
		t.Run(mode, func(t *testing.T) {
			dir := t.TempDir()
			path := filepath.Join(dir, "original.step")
			if out, e := exec.Command(bin, mode, path).CombinedOutput(); e != nil {
				t.Fatal(e, string(out))
			}
			raw, e := os.ReadFile(path)
			if e != nil {
				t.Fatal(e)
			}
			m, e := RepairPosedGroupedOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12})
			if e != nil {
				t.Fatal(e)
			}
			if len(m.Reversals()) != 2 || len(m.Tangencies()) != 8 {
				t.Fatal("owner evidence")
			}
			props, e := m.Solid().MassProperties(ctx, parametric.IntegrationOptions{})
			if e != nil {
				t.Fatal(e)
			}
			world := m.Descriptor().Frame.ToWorld(props.Centroid)
			var generated bytes.Buffer
			if e = WriteExactCircularLoopExtrusion(ctx, &generated, m.Descriptor()); e != nil {
				t.Fatal(e)
			}
			for name, data := range map[string][]byte{"original": raw, "corrected": []byte(m.CorrectedSTEP()), "generated": generated.Bytes()} {
				path := filepath.Join(dir, name+".step")
				if e = os.WriteFile(path, data, 0600); e != nil {
					t.Fatal(e)
				}
				out, e := exec.Command(bin, "read", path).CombinedOutput()
				if e != nil {
					t.Fatal(name, e, string(out))
				}
				at := bytes.LastIndex(out, []byte("{\"Volume\""))
				if at < 0 {
					t.Fatal(string(out))
				}
				var q struct {
					Volume, Area  float64
					Faces, Solids int
					Centroid      [3]float64
				}
				if e = json.Unmarshal(bytes.TrimSpace(out[at:]), &q); e != nil {
					t.Fatal(e)
				}
				if q.Faces != 7 || q.Solids != 1 || math.Abs(q.Volume-props.Volume) > 1e-8 || math.Abs(q.Area-props.Area) > 1e-8 || world.Distance(geom.Vec3{X: q.Centroid[0], Y: q.Centroid[1], Z: q.Centroid[2]}) > 1e-8 {
					t.Fatal(name, q, props, world)
				}
			}
		})
	}
}
func FuzzRepairGroupedOCCTConvexArc(f *testing.F) {
	raw, e := os.ReadFile("testdata/occt-model-only-two-oblique-prism-fillets.step")
	if e != nil {
		f.Fatal(e)
	}
	f.Add(raw)
	f.Add([]byte("ISO-10303-21;"))
	f.Fuzz(func(t *testing.T, raw []byte) {
		if len(raw) > 1<<20 {
			t.Skip()
		}
		m, e := RepairGroupedOCCTConvexArcExtrusion(context.Background(), bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12})
		if e != nil && m.OriginalSTEP() != "" {
			t.Fatal("partial failure")
		}
	})
}
