func TestNonplanarSplineShellOriginal(t *testing.T) {
	ctx := context.Background()
	raw := nonplanarRoofFixture(t)
	if _, e := ReadSplineShells(bytes.NewReader(raw), Limits{}); e == nil {
		t.Fatal("original LINE-only gate widened")
	}
	m, e := ReadNonplanarSplineShellSource(ctx, bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	if len(m.PCurves()) != 24 || len(m.SourceFaces()) != 6 || len(m.SourceEdges()) != 12 || m.OriginalSTEP() != string(raw) {
		t.Fatal("source roles")
	}
	mass, e := m.Model.Bodies[0].Solid.MassProperties(ctx, parametric.IntegrationOptions{})
	area := 12. + 56./3 + 15 + 3*math.Sqrt(5) + 12*math.Asinh(.5)
	if e != nil || math.Abs(mass.Volume-28) > 1e-10 || math.Abs(mass.Area-area) > 1e-7 || math.Abs(mass.Centroid.X-15./7) > 1e-10 || math.Abs(mass.Centroid.Z-83./70) > 1e-10 {
		t.Fatal(mass, e)
	}
	proof, e := m.Model.Bodies[0].Solid.ValidateEdgeAgreement(ctx, edgecheck.Options{})
	if e != nil || !proof.Complete {
		t.Fatal(e)
	}
	for _, u := range proof.Uses {
		if u.Report.SquaredUpperBound == nil || u.Report.SquaredUpperBound.Sign() != 0 {
			t.Fatal("nonzero continuous edge discrepancy")
		}
	}
	var native bytes.Buffer
	if e = WriteNonplanarSplineShellSourceJSON(ctx, &native, m); e != nil {
		t.Fatal(e)
	}
	loaded, e := ReadNonplanarSplineShellSourceJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	var again bytes.Buffer
	if e = WriteNonplanarSplineShellSourceJSON(ctx, &again, loaded); e != nil || !bytes.Equal(native.Bytes(), again.Bytes()) {
		t.Fatal("native stability", e)
	}
	var q nonplanarSplineShellEnvelope
	if e = json.Unmarshal(native.Bytes(), &q); e != nil {
		t.Fatal(e)
	}
	s, e := trimmed.ReadJSON(bytes.NewReader(q.Native), trimmed.JSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	p, e := s.ValidateSplineRectangleEmbedding(ctx, trimmed.SplineRectangleEmbeddingOptions{})
	if e != nil || !p.Complete {
		t.Fatal("native embedded material", e)
	}
	var source, generated bytes.Buffer
	if e = WriteNonplanarSplineShellSource(ctx, &source, loaded, Limits{}); e != nil || !bytes.Equal(raw, source.Bytes()) {
		t.Fatal("source", e)
	}
	if e = WriteSplineShells(&generated, loaded.Model); e != nil {
		t.Fatal(e)
	}
	if _, e = ReadSplineShells(bytes.NewReader(generated.Bytes()), Limits{}); e != nil {
		t.Fatal("generated", e)
	}
	f, e := Parse(bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	for i, j := 0, len(f.Order)-1; i < j; i, j = i+1, j-1 {
		f.Order[i], f.Order[j] = f.Order[j], f.Order[i]
	}
	reordered, e := mappedPlanarSourceBytes(f)
	if e != nil {
		t.Fatal(e)
	}
	if _, e = ReadNonplanarSplineShellSource(ctx, bytes.NewReader(reordered), Limits{}); e != nil {
		t.Fatal("record order", e)
	}
	cp := m.PCurves()
	cp[0].EdgeID++
	if cp[0].EdgeID == m.PCurves()[0].EdgeID {
		t.Fatal("mutable provenance")
	}
}
func TestNonplanarSplineShellReject(t *testing.T) {
	ctx := context.Background()
	raw := nonplanarRoofFixture(t)
	m, e := ReadNonplanarSplineShellSource(ctx, bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	pc := m.PCurves()[0]
	for name, edit := range map[string]func(*File){
		"wrong-speed":     func(f *File) { f.Entities[pc.CurveID].Records[0].Args[7].Items[1].Text = "2" },
		"wrong-owner":     func(f *File) { f.Entities[pc.PCurveID].Records[0].Args[1].Ref = m.PCurves()[1].SurfaceID },
		"near-coordinate": func(f *File) { f.Entities[pc.PoleIDs[1]].Records[0].Args[1].Items[0].Text = "1.000000000000000001" },
		"underflow":       func(f *File) { f.Entities[pc.PoleIDs[1]].Records[0].Args[1].Items[0].Text = "1.E-999999999" },
		"shared-pole":     func(f *File) { f.Entities[pc.CurveID].Records[0].Args[2].Items[1].Ref = m.PCurves()[1].PoleIDs[1] },
		"face-sense":      func(f *File) { f.Entities[m.faces[0]].Records[0].Args[3].Text = "F" },
		"roof-pole": func(f *File) {
			for _, id := range m.surfaces {
				r := f.Entities[id].Records[0]
				if noncoplanarSplinePoles(f, r) {
					pid := r.Args[3].Items[1].Items[0].Ref
					f.Entities[pid].Records[0].Args[1].Items[2].Text = "99"
					return
				}
			}
		},
		"orphan-point": func(f *File) {
			id := int64(999999)
			f.Entities[id] = Entity{ID: id, Records: []Record{{Type: "CARTESIAN_POINT", Args: []Value{{Kind: String}, {Kind: Aggregate, Items: []Value{{Kind: Number, Text: "0"}, {Kind: Number, Text: "0"}, {Kind: Number, Text: "0"}}}}}}}
			f.Order = append(f.Order, id)
		},
	} {
		t.Run(name, func(t *testing.T) {
			f, e := Parse(bytes.NewReader(raw), Limits{})
			if e != nil {
				t.Fatal(e)
			}
			edit(f)
			b, e := mappedPlanarSourceBytes(f)
			if e != nil {
				t.Fatal(e)
			}
			q, e := ReadNonplanarSplineShellSource(ctx, bytes.NewReader(b), Limits{})
			if e == nil || len(q.Model.Bodies) != 0 || q.original != "" {
				t.Fatal("admitted", e)
			}
		})
	}
	var native bytes.Buffer
	if e = WriteNonplanarSplineShellSourceJSON(ctx, &native, m); e != nil {
		t.Fatal(e)
	}
	for _, edit := range []func(*nonplanarSplineShellEnvelope){func(q *nonplanarSplineShellEnvelope) { q.Format = "other" }, func(q *nonplanarSplineShellEnvelope) { q.PCurves[0].EdgeID++ }, func(q *nonplanarSplineShellEnvelope) { q.Native = json.RawMessage(`{}`) }, func(q *nonplanarSplineShellEnvelope) { q.Canonical = "forged" }, func(q *nonplanarSplineShellEnvelope) { q.Source = "ISO-10303-21;" }} {
		var q nonplanarSplineShellEnvelope
		json.Unmarshal(native.Bytes(), &q)
		edit(&q)
		b, _ := json.Marshal(q)
		if _, e = ReadNonplanarSplineShellSourceJSON(ctx, bytes.NewReader(b), IndependentMaterialJSONLimits{}); e == nil {
			t.Fatal("native forgery")
		}
	}
	for _, l := range []Limits{{MaxBytes: 10}, {MaxEntities: 10}, {MaxValues: 100}, {MaxDepth: 1}, {MaxFaces: 5}, {MaxEdgeUses: 10}} {
		if _, e = ReadNonplanarSplineShellSource(ctx, bytes.NewReader(raw), l); e == nil {
			t.Fatal("limits")
		}
	}
	cctx, cancel := context.WithCancel(ctx)
	cancel()
	if _, e = ReadNonplanarSplineShellSource(cctx, bytes.NewReader(raw), Limits{}); e == nil {
		t.Fatal("cancel")
	}
	if _, e = ReadNonplanarSplineShellSourceJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{MaxBytes: 10}); e == nil {
		t.Fatal("native bytes")
	}
}
func TestNonplanarSplineShellLive(t *testing.T) {
	bin := os.Getenv("PLAINSOLID_OCCT_PARABOLIC_SPLINE_ROOF")
	if bin == "" {
		t.Skip("standalone OCCT helper")
	}
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "original.step")
	if b, e := exec.Command(bin, "write", path).CombinedOutput(); e != nil {
		t.Fatal(e, string(b))
	}
	raw, e := os.ReadFile(path)
	if e != nil {
		t.Fatal(e)
	}
	m, e := ReadNonplanarSplineShellSource(ctx, bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	var native bytes.Buffer
	if e = WriteNonplanarSplineShellSourceJSON(ctx, &native, m); e != nil {
		t.Fatal(e)
	}
	m, e = ReadNonplanarSplineShellSourceJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	for _, kind := range []string{"source", "generated"} {
		var out bytes.Buffer
		if kind == "source" {
			e = WriteNonplanarSplineShellSource(ctx, &out, m, Limits{})
		} else {
			e = WriteSplineShells(&out, m.Model)
		}
		if e != nil {
			t.Fatal(e)
		}
		p := filepath.Join(t.TempDir(), kind+".step")
		os.WriteFile(p, out.Bytes(), 0600)
		b, e := exec.Command(bin, "read", p).CombinedOutput()
		if e != nil {
			t.Fatal(e, string(b))
		}
		var report struct {
			Volume, Area  float64
			Faces, Solids int
			Centroid      [3]float64
		}
		lines := bytes.Split(b, []byte("\n"))
		found := false
		for _, line := range lines {
			if json.Unmarshal(line, &report) == nil && report.Solids == 1 {
				found = true
				break
			}
		}
		if !found || math.Abs(report.Volume-28) > 1e-9 || math.Abs(report.Area-58.14941249988128) > 1e-7 || report.Faces != 6 || math.Abs(report.Centroid[2]-83./70) > 1e-8 {
			t.Fatal(kind, string(b))
		}
	}
}
func FuzzNonplanarSplineShellSource(f *testing.F) {
	f.Add(nonplanarRoofFixture(f))
	f.Fuzz(func(t *testing.T, b []byte) {
		if len(b) > 1<<20 {
			t.Skip()
		}
		m, e := ReadNonplanarSplineShellSource(context.Background(), bytes.NewReader(b), Limits{})
		if e != nil {
			if m.original != "" || len(m.Model.Bodies) != 0 {
				t.Fatal("partial")
			}
			return
		}
		if len(m.Model.Bodies) != 1 || len(m.PCurves()) != 24 {
			t.Fatal("proof")
		}
	})
}
