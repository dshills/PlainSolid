package step

import (
	"bytes"
	"context"
	"encoding/json"
	"math"
	"plainsolid/brep/edgecheck"
	"plainsolid/brep/parametric"
	"plainsolid/brep/trimmed"
	"plainsolid/geom"
	"plainsolid/internal/slowtest"
	"testing"
)

func TestNonplanarSplineVoidsOriginal(t *testing.T) {
	slowtest.Skip(t)
	ctx := context.Background()
	raw := nonplanarVoidsFixture(t)
	m, e := ReadNonplanarSplineVoidsSource(ctx, bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	if _, e = ReadNonplanarSplineCavitySource(ctx, bytes.NewReader(raw), Limits{}); e == nil {
		t.Fatal("one-void route widened")
	}
	if _, e = ReadNonplanarSplineVoidsSource(ctx, bytes.NewReader(nonplanarCavityFixture(t)), Limits{}); e == nil {
		t.Fatal("one-void admitted")
	}
	if len(m.Voids) != 2 || len(m.SourceShells()) != 3 || len(m.PCurves()[2]) != 24 {
		t.Fatal("roles")
	}
	p, e := m.Solid.ValidateNestedSplineComponents(ctx, trimmed.SplineShellBooleanOptions{})
	if e != nil || len(p) != 3 {
		t.Fatal(p, e)
	}
	for i := 1; i < 3; i++ {
		if p[i].Parent != 0 || p[i].Depth != 1 {
			t.Fatal("void depth", p)
		}
	}
	mass, e := m.Solid.MassProperties(ctx, parametric.IntegrationOptions{})
	if e != nil || math.Abs(mass.Volume-3339./128) > 1e-10 || math.Abs(mass.Area-69.96101191391968) > 1e-7 || math.Abs(mass.Centroid.X-56737./26712) > 1e-10 || math.Abs(mass.Centroid.Y-217./144) > 1e-10 || math.Abs(mass.Centroid.Z-6149./5040) > 1e-10 {
		t.Fatal(mass, e)
	}
	proof, e := m.Solid.ValidateEdgeAgreement(ctx, edgecheck.Options{})
	if e != nil || !proof.Complete {
		t.Fatal(e)
	}
	for _, u := range proof.Uses {
		if u.Report.SquaredUpperBound == nil || u.Report.SquaredUpperBound.Sign() != 0 {
			t.Fatal("edge discrepancy")
		}
	}
	for i, body := range m.Voids {
		for j, fid := range m.NativeFaces()[i+1] {
			if m.Solid.Faces()[fid].Reversed == body.Solid.Faces()[j].Reversed {
				t.Fatal("void orientation")
			}
		}
	}
	for _, q := range []struct {
		p geom.Vec3
		l parametric.Location
	}{{geom.Vec3{X: 1.75, Y: .75, Z: .75}, parametric.Inside}, {geom.Vec3{X: 1, Y: .75, Z: .75}, parametric.Outside}, {geom.Vec3{X: 2.5, Y: 1.25, Z: .75}, parametric.Outside}} {
		got, e := m.Solid.LocateNestedSplineMaterial(ctx, q.p, trimmed.SplineShellBooleanOptions{})
		if e != nil || got != q.l {
			t.Fatal(q, got, e)
		}
	}
	var native bytes.Buffer
	if e = WriteNonplanarSplineVoidsSourceJSON(ctx, &native, m); e != nil {
		t.Fatal(e)
	}
	loaded, e := ReadNonplanarSplineVoidsSourceJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	var again bytes.Buffer
	if e = WriteNonplanarSplineVoidsSourceJSON(ctx, &again, loaded); e != nil || !bytes.Equal(native.Bytes(), again.Bytes()) {
		t.Fatal("stable native", e)
	}
	var q nonplanarSplineVoidsEnvelope
	json.Unmarshal(native.Bytes(), &q)
	ordinary, e := trimmed.ReadJSON(bytes.NewReader(q.Native), trimmed.JSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	p, e = ordinary.ValidateNestedSplineComponents(ctx, trimmed.SplineShellBooleanOptions{})
	if e != nil || len(p) != 3 || p[2].Depth != 1 {
		t.Fatal("ordinary native", e)
	}
	var source, generated bytes.Buffer
	if e = WriteNonplanarSplineVoidsSource(ctx, &source, loaded, Limits{}); e != nil || !bytes.Equal(raw, source.Bytes()) {
		t.Fatal("original source", e)
	}
	if e = WriteNonplanarSplineVoids(ctx, &generated, loaded, Limits{}); e != nil {
		t.Fatal(e)
	}
	if _, e = ReadNonplanarSplineVoidsSource(ctx, bytes.NewReader(generated.Bytes()), Limits{}); e != nil {
		t.Fatal("generated", e)
	}
	f, e := Parse(bytes.NewReader(raw), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	for i, j := 0, len(f.Order)-1; i < j; i, j = i+1, j-1 {
		f.Order[i], f.Order[j] = f.Order[j], f.Order[i]
	}
	v := f.Entities[m.bodyID].Records[0].Args[2].Items
	v[0], v[1] = v[1], v[0]
	b, e := mappedPlanarSourceBytes(f)
	if e != nil {
		t.Fatal(e)
	}
	reordered, e := ReadNonplanarSplineVoidsSource(ctx, bytes.NewReader(b), Limits{})
	if e != nil || reordered.SourceShells()[1] != m.SourceShells()[2] {
		t.Fatal("original list ordering", e)
	}
	faces := m.SourceFaces()
	faces[1][0]++
	nativeFaces := m.NativeFaces()
	nativeFaces[1][0]++
	uv := m.PCurves()
	uv[1][0].EdgeID++
	if faces[1][0] == m.SourceFaces()[1][0] || nativeFaces[1][0] == m.NativeFaces()[1][0] || uv[1][0].EdgeID == m.PCurves()[1][0].EdgeID {
		t.Fatal("mutable evidence")
	}
}
