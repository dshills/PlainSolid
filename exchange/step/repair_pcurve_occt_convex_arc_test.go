func TestRepairPCurveOCCTConvexArc(t *testing.T) {
	raw := pcurveConvexArcOriginal(t)
	ctx := context.Background()
	m, e := RepairPCurveOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12})
	if e != nil {
		t.Fatal(e)
	}
	if len(m.PCurves()) != 24 || len(m.Repairs()) != 3 || m.OriginalSTEP() != string(raw) {
		t.Fatal("complete original proof")
	}
	nonzero := 0
	for _, q := range m.PCurves() {
		if q.EdgeID == 0 || q.PCurveID == 0 || q.SurfaceCurveID == 0 || q.FaceID == 0 || q.SupportID == 0 || q.GeometryID == 0 {
			t.Fatal(q)
		}
		if q.DistanceSquaredUpper.Sign() != 0 {
			nonzero++
			lo, _ := new(big.Rat).SetString("2.3e-26")
			hi, _ := new(big.Rat).SetString("2.4e-26")
			if q.Kind != "cylinder-line" || q.DistanceSquaredUpper.Cmp(lo) < 0 || q.DistanceSquaredUpper.Cmp(hi) > 0 {
				t.Fatal(q)
			}
		}
	}
	if nonzero != 1 {
		t.Fatal(nonzero)
	}
	if _, e = RepairOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12}); e == nil {
		t.Fatal("model-only gate must stay strict")
	}
	if _, e = RepairPCurveOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-14}); e == nil {
		t.Fatal("pcurve budget must be enforced")
	}
	if _, e = RepairOCCTConvexArcExtrusion(ctx, bytes.NewBufferString(m.material.original), Limits{}, ConvexArcRepairOptions{1e-14}); e != nil {
		t.Fatal("separate smaller vertex-only budget", e)
	}
	var encoded bytes.Buffer
	if e = WritePCurveRepairedOCCTConvexArcJSON(ctx, &encoded, m); e != nil {
		t.Fatal(e)
	}
	reload, e := ReadPCurveRepairedOCCTConvexArcJSON(ctx, bytes.NewReader(encoded.Bytes()), IndependentMaterialJSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	var again bytes.Buffer
	if e = WritePCurveRepairedOCCTConvexArcJSON(ctx, &again, reload); e != nil || !bytes.Equal(encoded.Bytes(), again.Bytes()) {
		t.Fatal("stable source reproof", e)
	}
	if reload.OriginalSTEP() != string(raw) {
		t.Fatal("pcurves lost")
	}
	var generated bytes.Buffer
	if e = WriteExactCircularLoopExtrusion(ctx, &generated, reload.Descriptor()); e != nil {
		t.Fatal(e)
	}
	if _, e = ReadExactCircularLoopExtrusion(ctx, bytes.NewReader(generated.Bytes()), Limits{}); e != nil {
		t.Fatal(e)
	}
	m.PCurves()[0].DistanceSquaredUpper.SetInt64(99)
	if m.PCurves()[0].DistanceSquaredUpper.Sign() != 0 {
		t.Fatal("mutable proof")
	}
}
func TestRepairPCurveOCCTConvexArcReject(t *testing.T) {
	raw := pcurveConvexArcOriginal(t)
	ctx := context.Background()
	m, e := RepairPCurveOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12})
	if e != nil {
		t.Fatal(e)
	}
	first := m.PCurves()[0]
	var angular ConvexArcPCurveAgreement
	for _, q := range m.PCurves() {
		if q.DistanceSquaredUpper.Sign() != 0 {
			angular = q
		}
	}
	mutations := map[string]func(*File){
		"wrong owner": func(f *File) { f.Entities[first.PCurveID].Records[0].Args[1].Ref = first.GeometryID },
		"wrong UV speed": func(f *File) {
			g := f.Entities[first.GeometryID].Records[0]
			f.Entities[g.Args[2].Ref].Records[0].Args[2].Text = "2."
		},
		"reversed UV direction": func(f *File) {
			g := f.Entities[first.GeometryID].Records[0]
			v := f.Entities[g.Args[2].Ref].Records[0]
			d := f.Entities[v.Args[1].Ref].Records[0]
			for i, q := range d.Args[1].Items {
				r, err := liftSourceRat(q)
				if err != nil {
					t.Fatal(err)
				}
				d.Args[1].Items[i].Text = new(big.Rat).Neg(r).FloatString(16)
			}
		},
		"edge sense alone": func(f *File) {
			r := f.Entities[first.EdgeID].Records[0]
			if r.Args[4].Text == "T" {
				r.Args[4].Text = "F"
			} else {
				r.Args[4].Text = "T"
			}
		},
		"wrong UV phase": func(f *File) {
			g := f.Entities[angular.GeometryID].Records[0]
			f.Entities[g.Args[1].Ref].Records[0].Args[1].Items[0].Text = "2.498091544"
		},
		"wrong preferred curve": func(f *File) { f.Entities[first.SurfaceCurveID].Records[0].Args[3].Text = "CURVE_3D" },
		"duplicate owner": func(f *File) {
			r := &f.Entities[first.SurfaceCurveID].Records[0]
			r.Args[2].Items[1] = r.Args[2].Items[0]
		},
		"foreign model": func(f *File) { f.Entities[first.SurfaceCurveID].Records[0].Args[1].Ref = first.GeometryID },
		"bad context": func(f *File) {
			pc := f.Entities[first.PCurveID].Records[0]
			dr := f.Entities[pc.Args[2].Ref].Records[0]
			en := f.Entities[dr.Args[2].Ref]
			for i, r := range en.Records {
				if r.Type == "GEOMETRIC_REPRESENTATION_CONTEXT" {
					en.Records[i].Args[0].Text = "3"
				}
			}
			f.Entities[dr.Args[2].Ref] = en
		},
		"ignored geometry": func(f *File) {
			id := f.Order[len(f.Order)-1] + 1
			f.Entities[id] = Entity{ID: id, Records: []Record{{Type: "LINE", Args: []Value{{Kind: String}, {Kind: Reference, Ref: first.GeometryID}, {Kind: Reference, Ref: first.GeometryID}}}}}
			f.Order = append(f.Order, id)
		},
	}
	for name, mutate := range mutations {
		t.Run(name, func(t *testing.T) {
			f, e := Parse(bytes.NewReader(raw), Limits{})
			if e != nil {
				t.Fatal(e)
			}
			mutate(f)
			b, e := mappedPlanarSourceBytes(f)
			if e != nil {
				t.Fatal(e)
			}
			got, e := RepairPCurveOCCTConvexArcExtrusion(ctx, bytes.NewReader(b), Limits{}, ConvexArcRepairOptions{1e-12})
			if e == nil || got.OriginalSTEP() != "" {
				t.Fatal("accepted", e)
			}
		})
	}
	var encoded bytes.Buffer
	if e = WritePCurveRepairedOCCTConvexArcJSON(ctx, &encoded, m); e != nil {
		t.Fatal(e)
	}
	for _, name := range []string{"tag", "tolerance", "claims", "rational exponent", "source"} {
		t.Run(name, func(t *testing.T) {
			var q convexPCurveRepairEnvelope
			if e := json.Unmarshal(encoded.Bytes(), &q); e != nil {
				t.Fatal(e)
			}
			switch name {
			case "tag":
				q.Format = occtLoopNativeFormat
			case "tolerance":
				q.MaxDistance = 1e-14
			case "claims":
				q.Claims = json.RawMessage(`{"Native":{}}`)
			case "rational exponent":
				q.Claims = json.RawMessage(`{"PCurves":[{"DistanceSquaredUpper":"1e999999999"}]}`)
			case "source":
				q.Source = m.CorrectedModelSTEP()
			}
			b, _ := json.Marshal(q)
			got, e := ReadPCurveRepairedOCCTConvexArcJSON(ctx, bytes.NewReader(b), IndependentMaterialJSONLimits{})
			if e == nil || got.OriginalSTEP() != "" {
				t.Fatal("forged envelope", e)
			}
		})
	}
	c, cancel := context.WithCancel(ctx)
	cancel()
	if _, e = RepairPCurveOCCTConvexArcExtrusion(c, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12}); e != context.Canceled {
		t.Fatal(e)
	}
	if _, e = ReadPCurveRepairedOCCTConvexArcJSON(ctx, bytes.NewReader(encoded.Bytes()), IndependentMaterialJSONLimits{MaxBytes: 64}); e == nil {
		t.Fatal("native limit")
	}
	var out bytes.Buffer
	if e = WritePCurveRepairedOCCTConvexArcJSON(c, &out, m); e != context.Canceled || out.Len() != 0 {
		t.Fatal(e)
	}
	grouped, e := os.ReadFile("testdata/occt-both-default-oblique-prism-fillet.step")
	if e != nil {
		t.Fatal(e)
	}
	f, e := Parse(bytes.NewReader(grouped), Limits{})
	if e != nil {
		t.Fatal(e)
	}
	rational := 0
	for _, en := range f.Entities {
		for _, r := range en.Records {
			if r.Type == "RATIONAL_B_SPLINE_CURVE" {
				rational++
			}
		}
	}
	if rational != 2 {
		t.Fatal("retained real reversed pcurve obstacle", rational)
	}
	if _, e = RepairPCurveOCCTConvexArcExtrusion(ctx, bytes.NewReader(grouped), Limits{}, ConvexArcRepairOptions{1e-12}); e == nil {
		t.Fatal("unqualified grouped pcurves")
	}
}
func TestRepairPCurveOCCTConvexArcLive(t *testing.T) {
	bin := os.Getenv("PLAINSOLID_OCCT_CONVEX_ARC_ORIGINAL")
	if bin == "" {
		t.Skip("set pinned author/read comparator")
	}
	ctx := context.Background()
	dir := t.TempDir()
	path := filepath.Join(dir, "original.step")
	if out, e := exec.Command(bin, "write-default", path).CombinedOutput(); e != nil {
		t.Fatal(e, string(out))
	}
	raw, e := os.ReadFile(path)
	if e != nil {
		t.Fatal(e)
	}
	m, e := RepairPCurveOCCTConvexArcExtrusion(ctx, bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12})
	if e != nil {
		t.Fatal(e)
	}
	var native bytes.Buffer
	if e = WritePCurveRepairedOCCTConvexArcJSON(ctx, &native, m); e != nil {
		t.Fatal(e)
	}
	m, e = ReadPCurveRepairedOCCTConvexArcJSON(ctx, &native, IndependentMaterialJSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	var generated bytes.Buffer
	if e = WriteExactCircularLoopExtrusion(ctx, &generated, m.Descriptor()); e != nil {
		t.Fatal(e)
	}
	for name, data := range map[string][]byte{"original": []byte(m.OriginalSTEP()), "corrected-model": []byte(m.CorrectedModelSTEP()), "generated": generated.Bytes()} {
		path := filepath.Join(dir, name+".step")
		if e = os.WriteFile(path, data, 0600); e != nil {
			t.Fatal(e)
		}
		out, e := exec.Command(bin, "read", path).CombinedOutput()
		if e != nil {
			t.Fatal(name, e, string(out))
		}
		at := bytes.LastIndex(out, []byte("{\"Volume\""))
		if at < 0 {
			t.Fatal(string(out))
		}
		var q struct {
			Volume, Area  float64
			Faces, Solids int
		}
		if e = json.Unmarshal(bytes.TrimSpace(out[at:]), &q); e != nil {
			t.Fatal(e)
		}
		if q.Faces != 6 || q.Solids != 1 || math.Abs(q.Volume-29.145041881053835) > 1e-8 || math.Abs(q.Area-66.186284791166074) > 1e-8 {
			t.Fatal(name, q)
		}
	}
}
func FuzzRepairPCurveOCCTConvexArc(f *testing.F) {
	raw, e := os.ReadFile("testdata/occt-default-oblique-prism-fillet.step")
	if e != nil {
		f.Fatal(e)
	}
	f.Add(raw)
	f.Add([]byte("ISO-10303-21;"))
	f.Fuzz(func(t *testing.T, raw []byte) {
		if len(raw) > 1<<20 {
			t.Skip()
		}
		m, e := RepairPCurveOCCTConvexArcExtrusion(context.Background(), bytes.NewReader(raw), Limits{}, ConvexArcRepairOptions{1e-12})
		if e != nil && m.OriginalSTEP() != "" {
			t.Fatal("partial failure")
		}
	})
}
