func TestRepairGroupedPCurveOCCTConvexArc(t *testing.T) {
	ctx := context.Background()
	b, e := os.ReadFile("testdata/occt-both-default-oblique-prism-fillet.step")
	if e != nil {
		t.Fatal(e)
	}
	m, e := RepairGroupedPCurveOCCTConvexArcExtrusion(ctx, bytes.NewReader(b), Limits{}, ConvexArcRepairOptions{1e-12})
	if e != nil {
		t.Fatal(e)
	}
	if m.OriginalSTEP() != string(b) || len(m.PCurves()) != 28 || len(m.FiniteTrims()) != 2 || len(m.Repairs()) != 9 || len(m.Reversals()) != 2 || len(m.Tangencies()) != 8 {
		t.Fatal("ancestry")
	}
	var native bytes.Buffer
	if e = WriteGroupedPCurveRepairedOCCTConvexArcJSON(ctx, &native, m); e != nil {
		t.Fatal(e)
	}
	q, e := ReadGroupedPCurveRepairedOCCTConvexArcJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	var again bytes.Buffer
	if e = WriteGroupedPCurveRepairedOCCTConvexArcJSON(ctx, &again, q); e != nil || !bytes.Equal(native.Bytes(), again.Bytes()) {
		t.Fatal("canonical reproof", e)
	}
	trim := q.FiniteTrims()
	trim[0].EndPolynomial[0].SetInt64(55)
	trim[0].SourceEnd.Lower.SetInt64(55)
	trim[0].EndpointDistanceUpper[0].SetInt64(55)
	q.PCurves()[0].DistanceSquaredUpper.SetInt64(55)
	q.RationalCaps()[0].RadialDistanceUpper.SetInt64(55)
	q.RationalCaps()[0].Knots[0].SetInt64(55)
	again.Reset()
	if e = WriteGroupedPCurveRepairedOCCTConvexArcJSON(ctx, &again, q); e != nil || !bytes.Equal(native.Bytes(), again.Bytes()) {
		t.Fatal("mutable report", e)
	}
	var generated bytes.Buffer
	if e = WriteExactCircularLoopExtrusion(ctx, &generated, q.Descriptor()); e != nil {
		t.Fatal(e)
	}
	if _, e = ReadExactCircularLoopExtrusion(ctx, bytes.NewReader(generated.Bytes()), Limits{}); e != nil {
		t.Fatal(e)
	}
	for _, name := range []string{"old tag", "source", "tolerance", "proof", "native"} {
		t.Run(name, func(t *testing.T) {
			var env groupedPCurveRepairEnvelope
			if e := json.Unmarshal(native.Bytes(), &env); e != nil {
				t.Fatal(e)
			}
			switch name {
			case "old tag":
				env.Format = convexPCurveRepairFormat
			case "source":
				env.Source = m.CorrectedModelSTEP()
			case "tolerance":
				env.MaxDistance = 1e-14
			case "proof":
				env.Claims = json.RawMessage(`{"FiniteProof":{"Trims":[]}}`)
			case "native":
				env.Claims = json.RawMessage(`{"Native":{}}`)
			}
			bad, _ := json.Marshal(env)
			v, e := ReadGroupedPCurveRepairedOCCTConvexArcJSON(ctx, bytes.NewReader(bad), IndependentMaterialJSONLimits{})
			if e == nil || v.OriginalSTEP() != "" {
				t.Fatal("forged payload", e)
			}
		})
	}
	if _, e = ReadPCurveRepairedOCCTConvexArcJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{}); e == nil {
		t.Fatal("old format widened")
	}
	if _, e = ReadGroupedPCurveRepairedOCCTConvexArcJSON(ctx, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{MaxBytes: 64}); e == nil {
		t.Fatal("limit")
	}
	c, cancel := context.WithCancel(ctx)
	cancel()
	var empty bytes.Buffer
	if e = WriteGroupedPCurveRepairedOCCTConvexArcJSON(c, &empty, m); e != context.Canceled || empty.Len() != 0 {
		t.Fatal(e)
	}
	if _, e = ReadGroupedPCurveRepairedOCCTConvexArcJSON(c, bytes.NewReader(native.Bytes()), IndependentMaterialJSONLimits{}); e != context.Canceled {
		t.Fatal(e)
	}
	single, e := os.ReadFile("testdata/occt-default-oblique-prism-fillet.step")
	if e != nil {
		t.Fatal(e)
	}
	if _, e = RepairGroupedPCurveOCCTConvexArcExtrusion(ctx, bytes.NewReader(single), Limits{}, ConvexArcRepairOptions{1e-12}); e == nil {
		t.Fatal("single not grouped")
	}
}
func TestRepairGroupedPCurveOCCTConvexArcLive(t *testing.T) {
	bin := os.Getenv("PLAINSOLID_OCCT_CONVEX_ARC_ORIGINAL")
	if bin == "" {
		t.Skip("set pinned author")
	}
	ctx := context.Background()
	dir := t.TempDir()
	path := filepath.Join(dir, "original.step")
	if out, e := exec.Command(bin, "write-both-default", path).CombinedOutput(); e != nil {
		t.Fatal(e, string(out))
	}
	b, e := os.ReadFile(path)
	if e != nil {
		t.Fatal(e)
	}
	m, e := RepairGroupedPCurveOCCTConvexArcExtrusion(ctx, bytes.NewReader(b), Limits{}, ConvexArcRepairOptions{1e-12})
	if e != nil {
		t.Fatal(e)
	}
	var native bytes.Buffer
	if e = WriteGroupedPCurveRepairedOCCTConvexArcJSON(ctx, &native, m); e != nil {
		t.Fatal(e)
	}
	m, e = ReadGroupedPCurveRepairedOCCTConvexArcJSON(ctx, &native, IndependentMaterialJSONLimits{})
	if e != nil {
		t.Fatal(e)
	}
	var generated bytes.Buffer
	if e = WriteExactCircularLoopExtrusion(ctx, &generated, m.Descriptor()); e != nil {
		t.Fatal(e)
	}
	for name, b := range map[string][]byte{"original": []byte(m.OriginalSTEP()), "corrected": []byte(m.CorrectedModelSTEP()), "generated": generated.Bytes()} {
		path := filepath.Join(dir, name+".step")
		if e = os.WriteFile(path, b, 0600); e != nil {
			t.Fatal(e)
		}
		out, e := exec.Command(bin, "read", path).CombinedOutput()
		if e != nil {
			t.Fatal(e, string(out))
		}
		at := bytes.LastIndex(out, []byte("{\"Volume\""))
		if at < 0 {
			t.Fatal(string(out))
		}
		var v struct {
			Volume, Area  float64
			Faces, Solids int
		}
		if e = json.Unmarshal(bytes.TrimSpace(out[at:]), &v); e != nil {
			t.Fatal(e)
		}
		if v.Faces != 7 || v.Solids != 1 || math.Abs(v.Volume-29.077978807115535) > 1e-8 || math.Abs(v.Area-65.622954970084379) > 1e-8 {
			t.Fatal(name, v)
		}
	}
}
func FuzzGroupedPCurveNative(f *testing.F) {
	b, e := os.ReadFile("testdata/occt-both-default-oblique-prism-fillet.step")
	if e != nil {
		f.Fatal(e)
	}
	ctx := context.Background()
	m, e := RepairGroupedPCurveOCCTConvexArcExtrusion(ctx, bytes.NewReader(b), Limits{}, ConvexArcRepairOptions{1e-12})
	if e != nil {
		f.Fatal(e)
	}
	var raw bytes.Buffer
	if e = WriteGroupedPCurveRepairedOCCTConvexArcJSON(ctx, &raw, m); e != nil {
		f.Fatal(e)
	}
	f.Add(raw.Bytes())
	f.Add([]byte(`{"Format":"bad"}`))
	f.Fuzz(func(t *testing.T, b []byte) {
		if len(b) > 1<<20 {
			t.Skip()
		}
		q, e := ReadGroupedPCurveRepairedOCCTConvexArcJSON(ctx, bytes.NewReader(b), IndependentMaterialJSONLimits{MaxBytes: 1 << 20})
		if e != nil && q.OriginalSTEP() != "" {
			t.Fatal("partial payload")
		}
	})
}
