package exchange

import (
	"bytes"
	"context"
	"errors"
	"math"
	"testing"

	"plainsolid/brep/parametric"
	"plainsolid/collision"
	"plainsolid/geom"
)

func TestCylinderPairCavityRecipe(t *testing.T) {
	ctx := context.Background()
	stock := geom.RawCylinder{Origin: geom.Vec3{X: 1, Y: 2, Z: 3}, Axis: geom.Vec3{Z: -2}, Radius: 5, Min: -2, Max: 2}
	cutter := geom.RawCylinder{Origin: geom.Vec3{X: 2, Y: 2.5, Z: 2}, Axis: geom.Vec3{Z: -1}, Radius: 2, Min: 0, Max: 2}
	r := CylinderPairCommonRecipe{Name: "signed enclosed cavity", A: stock, B: cutter, Tolerance: 1e-9, LengthUnit: .001}
	var original, regenerated bytes.Buffer
	if err := WriteCylinderPairDifferenceRecipeJSON(ctx, &original, r); err != nil {
		t.Fatal(err)
	}
	got, d, err := ReadCylinderPairDifferenceRecipeJSON(ctx, bytes.NewReader(original.Bytes()), 0)
	if err != nil || got != r || len(d.Solids[0].Faces()) != 6 || len(d.Solids[1].Faces()) != 0 || len(d.CutterCapFaces[0]) != 2 || len(d.CutterCapFaces[1]) != 0 {
		t.Fatal("cavity recipe and ancestry", err)
	}
	if err = WriteCylinderPairDifferenceRecipeJSON(ctx, &regenerated, got); err != nil || !bytes.Equal(original.Bytes(), regenerated.Bytes()) {
		t.Fatal("noncanonical round trip", err)
	}
	s := d.Solids[0]
	for i, id := range d.CutterCapFaces[0] {
		f := s.Faces()[id]
		p, err := f.Surface.Eval(0, 0)
		if err != nil || p.Z != [2]float64{2, 0}[i] {
			t.Fatal("lost original cutter cap order", i, p, err)
		}
	}
	m, err := s.MassProperties(ctx, parametric.IntegrationOptions{})
	wantCenter := stock.Origin.Sub(geom.Vec3{X: 1, Y: .5, Z: -2}.Scale(8.0 / 192))
	if err != nil || math.Abs(m.Area-146*math.Pi) > 1e-8 || math.Abs(m.Volume-192*math.Pi) > 1e-8 || m.Centroid.Sub(wantCenter).Length() > 1e-9 {
		t.Fatal("inward cavity measures", m, err)
	}
	display, err := s.Tessellate(ctx, parametric.TessellationOptions{Deflection: .5, AnalyticBound: true})
	if err != nil || display.ValidateSolid() != nil {
		t.Fatal("closed cavity display", err)
	}
	contacts, err := collision.SelfIntersectionsBVHContext(ctx, display, collision.Options{})
	if err != nil || !contacts.Complete || len(contacts.Contacts) != 0 {
		t.Fatal("embedded cavity display", err)
	}
	// Exactly reaching a stock cap is now qualified as an open blind bore,
	// whereas radial tangency still cannot publish a pinched cavity.
	open := cutter
	open.Max = 3
	other, err := parametric.FiniteCylinderPairDifference(ctx, stock, open, 1e-9)
	if err != nil || len(other.Solids[0].Faces()) != 20 || len(other.CutterCapFaces[0]) != 4 {
		t.Fatal("cap contact must open the bore", err)
	}
	tangent := cutter
	tangent.Origin = geom.Vec3{X: 4, Y: 2, Z: 2}
	bad, err := parametric.FiniteCylinderPairDifference(ctx, stock, tangent, 1e-9)
	if !errors.Is(err, geom.ErrDomain) || len(bad.Solids[0].Faces()) != 0 {
		t.Fatal("radial contact published an unproved cavity", err)
	}
}
